        /// <summary>
        /// How many read-back textures and assembled segment meshes may wait to be written.
        /// Each holds a full uncompressed payload — a texture's pixels at four bytes each, or a
        /// segment's vertex arrays — so an unbounded queue only moves the memory problem; the
        /// reader pauses when it is full, exactly as the mesh rip's does.
        /// </summary>
        private const int QueueCapacity = 8;

        /// <summary>
        /// The rip in flight, or <c>null</c>.
        /// </summary>
        NetworkRun _run;

        /// <summary>
        /// Whether a rip is running.
        /// </summary>
        public bool IsRipping => _run != null;

        /// <summary>
        /// How long a single frame may spend advancing a rip, in milliseconds.
        /// A budget rather than a fixed count of edges: a junction of a wide road costs many times
        /// what a straight footpath does, so a fixed count would stutter on exactly the parts of a
        /// city that are worth watching.
        /// </summary>
        private const double FrameBudgetMs = 12d;

        /// <summary>
        /// The event triggered when the system instance is destroyed.
        /// A rip in flight holds an open file, so it has to be closed here — the user quitting to
        /// the menu mid-rip is otherwise a truncated <c>networks.jsonl</c>.
        /// </summary>
        protected override void OnDestroy()
        {
            NetworkRun run = _run;
            _run = null;

            if (run != null)
            {
                _log.Info($"Network rip abandoned at {run.Index}/{run.Edges.Length} edge(s); the world was unloaded.");
                Instance.MeshRip.WarningSink = null;
                run.Writer?.Dispose();
                run.LaneWriter?.Dispose();

                // The writer is a live thread blocked on the queue, so abandoning the run without
                // closing it leaves it there for the rest of the session.
                //
                Drain(run);
                RipProgress.Clear();
            }

            base.OnDestroy();
        }

        /// <summary>
        /// Drive the progress indicator, and advance any rip in progress by one frame's worth.
        /// </summary>
        protected override void OnUpdate()
        {
            RipProgress.Pump();

            NetworkRun run = _run;
            if (run != null) Advance(run);
        }

        /// <summary>
        /// Start a network rip, returning at once.
        /// </summary>
        /// <param name="outputDirectory">The bundle root to write into.</param>
        /// <param name="textureSizeCap">The longest edge a written texture may have, <c>0</c> for no cap, or negative to write no textures.</param>
        /// <param name="completed">Receives the finish summary instead of a dialog when a pipeline drives the rip.</param>
        /// <param name="surfaces">Whether to assemble the road/rail/path surfaces (networks.jsonl + networks/).</param>
        /// <param name="laneGeometry">Whether to bake lane-drawn furniture (lanemeshes layer).</param>
        /// <param name="laneDecals">Whether the lane catalogue carries decal parts — road markings and wear.</param>
        /// <returns>What the caller should tell the user.</returns>
        public string BeginRip(string outputDirectory, int textureSizeCap = 2048, Action<string> completed = null,
                               bool surfaces = true, bool laneGeometry = true, bool laneDecals = true)
        {
            if (_run != null) return "A network rip is already running.";
            if (!surfaces && !laneGeometry) return "Nothing selected: both the network surfaces and the lane geometry are deselected.";

            // The material table has one owner at a time. A cross-section piece reads through the
            // same `MeshRipSystem.ReadMesh` a building does, and that only resolves a material when
            // a material run is in flight — so without one, every road's primitives keep the
            // synthetic `<piece>_mat0` id, nothing declares it, and the roads import untextured.
            //
            if (Instance.MeshRip.IsRipping)
                return "A mesh rip is running. Wait for it to finish — the two share the material table.";

            RipProgress.Report(RipProgress.Phase.Scan);
            // Keyed by piece entity; entities can be reused across runs, so the cache is per-rip.
            //
            m_PieceGeometry.Clear();
            _rotatedEdges = 0;
            _roundaboutParts = 0;
            _skipBottomPieces = 0;
            _railPieces = 0;
            _orphanCaps = 0;
            _pipelineCompositions = 0;
            _lowerBottomPieces = 0;
            _raiseTopPieces = 0;
            _conformLoweredVerts = 0;
            _conformKeptVerts = 0;
            _conformRaisedVerts = 0;
            _conformOutOfWindowTris = 0;
            m_ConformProbes.Clear();

            // A deselected half simply contributes an empty work list; the pipeline shares the
            // rest — writers, materials, progress — unchanged.
            //
            Entity[] edges = Array.Empty<Entity>(), orphans = Array.Empty<Entity>(), lanes = Array.Empty<Entity>();

            if (surfaces)
            {
                NativeArray<Entity> entities = _edgeQuery.ToEntityArray(Allocator.TempJob);
                try
                {
                    edges = entities.ToArray();
                }
                finally
                {
                    entities.Dispose();
                }

                NativeArray<Entity> orphanEntities = _orphanQuery.ToEntityArray(Allocator.TempJob);
                try
                {
                    orphans = orphanEntities.ToArray();
                }
                finally
                {
                    orphanEntities.Dispose();
                }
            }

            if (laneGeometry)
            {
                NativeArray<Entity> laneEntities = _laneQuery.ToEntityArray(Allocator.TempJob);
                try
                {
                    lanes = laneEntities.ToArray();
                }
                finally
                {
                    laneEntities.Dispose();
                }
            }

            NetworkRun run = new()
            {
                Edges = edges,
                Orphans = orphans,
                Lanes = lanes,
                OutputDirectory = outputDirectory,
                MeshDirectory = IOUtils.CombinePath(outputDirectory, "networks"),
                LaneMeshDirectory = IOUtils.CombinePath(outputDirectory, "lanemeshes"),
                // A deselected half's writer is never created: constructing it would truncate a
                // file an earlier rip legitimately left there.
                Writer = surfaces ? new NetworkWriter(IOUtils.CombinePath(outputDirectory, "networks.jsonl")) : null,
                LaneWriter = laneGeometry ? new NetworkWriter(IOUtils.CombinePath(outputDirectory, "lanemeshes.jsonl")) : null,
                Materials = Instance.MaterialRip,
                IncludeLaneDecals = laneDecals,
                Completed = completed
            };

            run.Report.AppendLine($"Network edges: {edges.Length}");

            // Materials ride along, as they do for meshes: a piece's surface assets are reached
            // through the very render prefab its geometry came from. The writer runs off the main
            // thread because a texture is read back on it and compressed off it, and it serialises
            // the segment meshes too so that each one is written after the textures it names.
            //
            run.Queue = new BlockingCollection<NetworkItem>(QueueCapacity);
            Instance.MaterialRip.Begin(outputDirectory, textureSizeCap,
                                       texture => run.Queue.Add(new NetworkItem { Texture = texture }));

            // Partial reads inside `ReadMesh` (lane part meshes read this way) must land in this
            // run's warnings — without a mesh run in flight they had nowhere to go (§10).
            //
            Instance.MeshRip.WarningSink = run.Skipped;

            run.Encoder = Task.Run(() => Encode(run));

            _run = run;
            RipProgress.Report(RipProgress.Phase.Networks, 0, edges.Length + orphans.Length + lanes.Length);

            return $"Ripping {edges.Length} network edge(s), {orphans.Length} orphan node(s) "
                 + $"and the drawn geometry of {lanes.Length} lane(s).\n\n"
                 + "Progress shows in the corner; a dialog reports the result when it finishes.";
        }

        /// <summary>
        /// Advance a rip by one frame's budget.
        /// </summary>
        /// <param name="run">The rip in flight.</param>
        private void Advance(NetworkRun run)
        {
            double started = run.Clock.Elapsed.TotalMilliseconds;

            while (run.Index < run.Edges.Length)
            {
                RipOne(run, run.Edges[run.Index]);
                run.Index++;

                if ((run.Clock.Elapsed.TotalMilliseconds - started) >= FrameBudgetMs) break;
            }

            // Orphan caps after the edges, under the same frame budget.
            //
            if (run.Index >= run.Edges.Length)
            {
                while ((run.OrphanIndex < run.Orphans.Length)
                       && ((run.Clock.Elapsed.TotalMilliseconds - started) < FrameBudgetMs))
                {
                    RipOrphan(run, run.Orphans[run.OrphanIndex]);
                    run.OrphanIndex++;
                }
            }

            // Lane-drawn geometry last, still under the same budget: hanging utility cables,
            // fence and hedge lanes, bent along their curves the way the game bends them.
            //
            if ((run.Index >= run.Edges.Length) && (run.OrphanIndex >= run.Orphans.Length))
            {
                while ((run.LaneIndex < run.Lanes.Length)
                       && ((run.Clock.Elapsed.TotalMilliseconds - started) < FrameBudgetMs))
                {
                    RipLaneGeometry(run, run.Lanes[run.LaneIndex]);
                    run.LaneIndex++;
                }
            }

            RipProgress.Report(RipProgress.Phase.Networks, run.Index + run.OrphanIndex + run.LaneIndex,
                               run.Edges.Length + run.Orphans.Length + run.Lanes.Length);

            if ((run.Index >= run.Edges.Length) && (run.OrphanIndex >= run.Orphans.Length)
                && (run.LaneIndex >= run.Lanes.Length)) Finish(run);
        }

        /// <summary>
        /// Rip one network edge into the run.
        /// </summary>
        /// <param name="run">The rip in flight.</param>
        /// <param name="entity">The edge to rip.</param>
        private void RipOne(NetworkRun run, Entity entity)
        {
                {
                    // The work list is captured once and then worked through over many frames, so
                    // the world moves underneath it: the simulation deletes and rebuilds net
                    // entities as it runs, and an edge captured at the start may be gone by the
                    // time its turn comes. Nothing in ECS makes a stale Entity safe to ask about —
                    // it faults inside EntityComponentStore rather than answering false — so the
                    // liveness check has to come first.
                    //
                    if (!EntityManager.Exists(entity))
                    {
                        run.SkippedStale++;
                        return;
                    }

                    Composition composition = EntityManager.GetComponentData<Composition>(entity);
                    Entity edgeComposition = composition.m_Edge;
                    bool isTaxiway = (edgeComposition != Entity.Null)
                                  && EntityManager.HasComponent<TaxiwayComposition>(edgeComposition);

                    // Network markers — pipe and cable junction anchors, and airspace — are the
                    // same invisible simulation furniture the instance rip drops, so the two
                    // layers agree on what "the built environment" means. Taxiways carry the
                    // marker component and are genuinely drawn, which is why they are the one
                    // exception, exactly as the vector export has it.
                    //
                    if (EntityManager.HasComponent<Game.Net.Marker>(entity) && !isTaxiway)
                    {
                        run.SkippedMarker++;
                        return;
                    }

                    if (isTaxiway
                        && ((EntityManager.GetComponentData<TaxiwayComposition>(edgeComposition).m_Flags & TaxiwayFlags.Airspace) != 0))
                    {
                        run.SkippedMarker++;
                        return;
                    }

                    EdgeGeometry geometry = EntityManager.GetComponentData<EdgeGeometry>(entity);
                    Edge edge = EntityManager.GetComponentData<Edge>(entity);
                    float3 center = Colossal.Mathematics.MathUtils.Center(geometry.m_Bounds);

                    float width = GetWidth(edgeComposition, entity, geometry);
                    if (!(width > 0f))
                    {
                        // The schema's centerline form requires a positive width, since a consumer
                        // extrudes by it; a zero-width run is nothing anyone can draw.
                        //
                        run.SkippedNoWidth++;
                        return;
                    }

                    NetworkRecord record = new() { Id = entity.Index, Kind = "segment" };

                    // Mesh form where the network has a cross-section to assemble, centerline form
                    // where it does not. The contract allows a bundle to mix them freely and this
                    // is what that is for: a road, a rail line or a path is built from pieces and
                    // becomes real geometry, while a pipe or a cable has no surface at all and is
                    // only ever a line the consumer extrudes.
                    //
                    string assetId = $"seg_{entity.Index}";
                    MeshAsset assembled = AssembleNetwork(entity, geometry, center, assetId, run.PieceCache, null);

                    if (assembled != null)
                    {
                        // Handed to the writer rather than serialised here: assembling the edge has
                        // just queued its pieces' textures, and the .glb can only name them once
                        // they carry a content hash. See NetworkItem.
                        //
                        run.Queue.Add(new NetworkItem { Mesh = assembled });
                        record.AssetId = assetId;
                        record.Position = center;
                        record.Rotation = quaternion.identity;
                        run.Triangles += assembled.TriangleCount;
                    }
                    else
                    {
                        List<float3> centerline = BuildCenterline(entity, edge, geometry);
                        if (centerline.Count < 2)
                        {
                            run.SkippedDegenerate++;
                            return;
                        }

                        record.Centerline = centerline;
                        record.Width = width;
                        run.Points += centerline.Count;
                    }

                    AddAttributes(entity, edgeComposition, width, record, run.AggregateNames);

                    run.Writer.Write(record);

                    string category = record.Attributes.TryGetValue("category", out object c) ? c.ToString() : "other";
                    run.ByCategory.TryGetValue(category, out int categoryCount);
                    run.ByCategory[category] = categoryCount + 1;

                    string form = record.Attributes.TryGetValue("form", out object f) ? f.ToString() : "normal";
                    run.ByForm.TryGetValue(form, out int formCount);
                    run.ByForm[form] = formCount + 1;
                }

        }

        /// <summary>
        /// Rip one orphan node — a node no edge connects to — as the two half-disc caps the game
        /// draws for it.
        /// The geometry is <c>CalculateOrphanParameters</c>, decompiled: each half is a quarter
        /// circle of béziers from one side of the node around to its apex, ruled against a
        /// degenerate curve at the node's centre, and the node composition's pieces bend across
        /// that exactly as they bend across a flare. The circle is built in world axes from the
        /// node position and the composition width, which is the game's own construction — the
        /// cap does not turn with the node.
        /// </summary>
        /// <param name="run">The rip in flight.</param>
        /// <param name="entity">The orphan node entity.</param>
        private void RipOrphan(NetworkRun run, Entity entity)
        {
            if (!EntityManager.Exists(entity) || !EntityManager.HasComponent<Game.Net.Orphan>(entity)
                || !EntityManager.HasComponent<Node>(entity))
            {
                run.SkippedStale++;
                return;
            }

            if (EntityManager.HasComponent<Game.Net.Marker>(entity))
            {
                run.SkippedMarker++;
                return;
            }

            Entity composition = EntityManager.GetComponentData<Game.Net.Orphan>(entity).m_Composition;
            if ((composition == Entity.Null) || !EntityManager.HasComponent<NetCompositionData>(composition))
            {
                run.SkippedDegenerate++;
                return;
            }

            float width = EntityManager.GetComponentData<NetCompositionData>(composition).m_Width;
            if (!(width > 0f))
            {
                run.SkippedNoWidth++;
                return;
            }

            float3 position = EntityManager.GetComponentData<Node>(entity).m_Position;

            List<float3> vertices = new();
            List<float2> uvs = new();
            List<int> indices = new();
            List<MeshPrimitive> primitives = new();

            AppendOrphanHalf(composition, position, width, true, run.PieceCache,
                             vertices, uvs, indices, primitives);
            AppendOrphanHalf(composition, position, width, false, run.PieceCache,
                             vertices, uvs, indices, primitives);

            string assetId = $"orphan_{entity.Index}";
            MeshAsset assembled = Finish(assetId, vertices, uvs, indices, primitives);
            if (assembled == null)
            {
                run.SkippedDegenerate++;
                return;
            }

            run.Queue.Add(new NetworkItem { Mesh = assembled });
            run.Triangles += assembled.TriangleCount;
            _orphanCaps++;

            Entity prefab = EntityManager.GetComponentData<PrefabRef>(entity).m_Prefab;
            NetworkRecord record = new()
            {
                Id = entity.Index,
                Kind = "segment",
                AssetId = assetId,
                Position = position,
                Rotation = quaternion.identity
            };

            string asset = Instance.Name.GetPrefabName(prefab);
            if (!string.IsNullOrEmpty(asset)) record.Attributes["asset"] = asset;
            record.Attributes["category"] = GetCategory(prefab, composition);
            record.Attributes["form"] = "normal";
            record.Attributes["width"] = Math.Round((double)width, 3);

            run.Writer.Write(record);

            string category = record.Attributes["category"].ToString();
            run.ByCategory.TryGetValue(category, out int categoryCount);
            run.ByCategory[category] = categoryCount + 1;
            run.ByForm.TryGetValue("normal", out int formCount);
            run.ByForm["normal"] = formCount + 1;
        }

        /// <summary>
        /// One half of an orphan cap, built from the game's own synthetic segments.
        /// </summary>
        /// <param name="composition">The orphan's composition.</param>
        /// <param name="position">The node position.</param>
        /// <param name="width">The composition width.</param>
        /// <param name="primary">Whether this is the +z half.</param>
        /// <param name="cache">The piece mesh cache.</param>
        /// <param name="vertices">The shared vertex list.</param>
        /// <param name="uvs">The shared UV list.</param>
        /// <param name="indices">The shared index list.</param>
        /// <param name="primitives">The shared primitive list.</param>
        private void AppendOrphanHalf(Entity composition, float3 position, float width, bool primary,
                                      Dictionary<Entity, MeshAsset> cache, List<float3> vertices,
                                      List<float2> uvs, List<int> indices, List<MeshPrimitive> primitives)
        {
            // The game's own `CalculateOrphanParameters`, ported in NetworkRipSystem.GameMesh.cs
            // — the four-cubic circle segments, corner rails and mapping tables come from there.
            //
            if ((composition == Entity.Null) || !EntityManager.HasComponent<NetCompositionData>(composition)) return;

            NetCompositionData data = EntityManager.GetComponentData<NetCompositionData>(composition);
            CompositionCurves curves = OrphanCurves(position, data, primary);
            BuildGameComposition(composition, curves, position,
                                 primary ? "orphan+" : "orphan-", cache,
                                 vertices, uvs, indices, primitives, null);
        }

        /// <summary>
        /// Close the file, report, and tell the user what came out.
        /// </summary>
        /// <param name="run">The finished run.</param>
        private void Finish(NetworkRun run)
        {
            _run = null;
            Instance.MeshRip.WarningSink = null;
            run.Clock.Stop();
            RipProgress.Clear();
            run.Writer?.Dispose();
            run.LaneWriter?.Dispose();

            // Materials last: the table can only name a texture by the content hash of the file it
            // became, so it is written once the writer has drained. Draining also flushes the last
            // segment meshes, which is why the byte count below is only final afterwards.
            //
            string materials = Drain(run);

            // The lane prefab catalogue (contract §5B v2): the straight parts and prefab-level
            // bend inputs every lanemeshes.jsonl record references by key.
            //
            if (run.LaneCatalogue.Count > 0)
            {
                try
                {
                    System.IO.File.WriteAllText(
                        IOUtils.CombinePath(run.OutputDirectory, "laneprefabs.json"),
                        Newtonsoft.Json.JsonConvert.SerializeObject(run.LaneCatalogue));
                }
                catch (Exception ex)
                {
                    _log.Error($"Could not write laneprefabs.json: {ex.Message}");
                }
            }

            StringBuilder report = run.Report;
            if (run.Writer != null)
            {
                report.AppendLine($"Wrote {run.Writer.Count} segment(s) to networks.jsonl in {run.Clock.Elapsed.TotalSeconds:F1} s");
                report.AppendLine($"  mesh form: {run.Writer.MeshForm} ({run.Triangles} triangles, "
                                + $"{run.Bytes / 1048576d:F1} MiB of glTF in networks/)");
                report.AppendLine($"  centerline form: {run.Writer.CenterlineForm} ({run.Points} point(s))");
            }
            else
            {
                report.AppendLine("Network surfaces deselected — networks.jsonl untouched.");
            }
            report.AppendLine($"Distinct cross-section pieces read: {run.PieceCache.Count}");
            report.AppendLine("Junction interiors are the arms' own node meshes, tiled to the centre "
                            + "(zero-width intersection pieces as three-rail wedges; audit §18)");
            if (_rotatedEdges > 0) report.AppendLine($"Rotated edges assembled: {_rotatedEdges}");
            if (_orphanCaps > 0) report.AppendLine($"Orphan node caps: {_orphanCaps}");

            // The lane-geometry stage: parameter records referencing part meshes stored once
            // (contract §5B v2); the consumer bends.
            //
            if ((run.LaneWriter != null) && ((run.LaneWriter.Count > 0) || (run.SkippedLanePipeline + run.SkippedLaneDecal > 0)))
            {
                report.AppendLine($"Lane geometry: {run.LaneWriter.Count} lane record(s) over "
                                + $"{run.LaneCatalogue.Count} prefab(s) in laneprefabs.json, "
                                + $"{run.LaneMeshIds.Count} part mesh(es) written once into lanemeshes/ "
                                + $"({run.LaneBytes / 1048576d:F1} MiB)");
                foreach (KeyValuePair<string, int> kvp in run.LanesByCategory) report.AppendLine($"  {kvp.Key}: {kvp.Value}");
                if (run.LaneHanging > 0) report.AppendLine($"  hanging (calm-air drop; the consumer builds the cubic): {run.LaneHanging}");
                if (run.LaneTunnel > 0) report.AppendLine($"  included {run.LaneTunnel} tunnel lane(s), tagged \"tunnel\" (the game draws them on its Tunnel cutaway layer)");
                if (run.LaneWorn > 0) report.AppendLine($"  {run.LaneWorn} lane(s) carry non-zero road wear (\"wear\", raw 0..10; tint = wear/10)");
                if (run.SkippedLanePipeline > 0) report.AppendLine($"  excluded {run.SkippedLanePipeline} part(s) with no world-view layer from the catalogue (Pipeline/SubPipeline/Waterway)");
                if (run.SkippedLaneDecal > 0) report.AppendLine(run.IncludeLaneDecals
                    ? $"  {run.SkippedLaneDecal} decal part(s) in the catalogue — wear tint and road markings, lifted by the consumer (§5B)"
                    : $"  excluded {run.SkippedLaneDecal} decal part(s) by the layer selection (lane decals toggle)");
                if (run.SkippedLaneExcluded > 0) report.AppendLine($"  skipped {run.SkippedLaneExcluded} lane(s) whose parts its flags all exclude (drawn nowhere in-game either)");
                if (run.SkippedLaneStale > 0) report.AppendLine($"  skipped {run.SkippedLaneStale} lane(s) the simulation removed mid-rip");
                if (run.SkippedLaneDegenerate > 0) report.AppendLine($"  skipped {run.SkippedLaneDegenerate} lane(s) under the game's 0.1 m draw gate");
            }

            // Game rules seen but not reproduced — the numbers say whether the gap matters in
            // this city.
            if (_roundaboutParts > 0) report.AppendLine($"APPROXIMATED: {_roundaboutParts} roundabout part(s) — "
                                                      + "halves + wedge cover outer/inner/island; blend weights are shader-side");
            if (_railPieces > 0) report.AppendLine($"Corner-rail (PreserveShape) pieces placed: {_railPieces}");
            if (_skipBottomPieces > 0) report.AppendLine($"SkipBottomHalf pieces halved: {_skipBottomPieces}");
            if (_lowerBottomPieces + _raiseTopPieces > 0)
            {
                report.AppendLine($"{_lowerBottomPieces} LowerBottomToTerrain / {_raiseTopPieces} RaiseTopToTerrain "
                                + $"piece(s) conformed at rip time (BatchMeshHelpers' per-slice height bounds "
                                + "+ the vertex shader's terrain sample, applied here):");
                report.AppendLine($"  bottom edges (clamp DOWN only — a trench wall's base never lifts, §38): "
                                + $"{_conformLoweredVerts} vertex(es) buried, {_conformKeptVerts} kept at road level");
                report.AppendLine($"  top edges (pinned to the terrain both ways — the §34 portal stretch): "
                                + $"{_conformRaisedVerts} vertex(es)");
                if (_conformOutOfWindowTris > 0)
                    report.AppendLine($"  DATA-CONTRACT VIOLATION: {_conformOutOfWindowTris} triangle(s) referenced "
                                    + "vertices outside their material range and were dropped (expected 0; "
                                    + "every scanned .Geometry asset keeps its ranges self-contained)");

                // One row per flagged piece — the §38 probe. A piece whose vertices ALL
                // classify is a two-rail wall: its whole shape is the conform move, so it is
                // the first suspect when a wall looks wrong.
                //
                List<KeyValuePair<string, ConformPieceProbe>> probes = new(m_ConformProbes);
                probes.Sort((a, b) => string.CompareOrdinal(a.Key, b.Key));
                foreach (KeyValuePair<string, ConformPieceProbe> kvp in probes)
                {
                    ConformPieceProbe pr = kvp.Value;
                    int classified = pr.Class1 + pr.Class2;
                    string share = (pr.Vertices > 0) ? $"{100f * classified / pr.Vertices:F0}%" : "n/a";
                    string twoRail = ((pr.Vertices > 0) && (classified == pr.Vertices)) ? " [TWO-RAIL: 100% classified]" : "";
                    report.AppendLine($"  {kvp.Key}: {pr.Flags}, size {pr.Size.x:F1}x{pr.Size.y:F1}x{pr.Size.z:F1}, "
                                    + $"{pr.Vertices} vert(s), class-1 {pr.Class1} / class-2 {pr.Class2} ({share}){twoRail}; "
                                    + $"{pr.Lowered} buried / {pr.Kept} kept / {pr.Raised} raised; "
                                    + $"dropped tris {pr.FrontCutTris} front / {pr.BackCutTris} back / {pr.OutOfWindowTris} window");
                }
            }
            if (_pipelineCompositions > 0)
                report.AppendLine($"Skipped {_pipelineCompositions} composition part(s) with no world-view layer "
                                + "(Pipeline/SubPipeline/Waterway — utility cutaway and overlay views only; "
                                + "Tunnel compositions are world geometry and included)");

            foreach (KeyValuePair<string, int> kvp in run.ByCategory) report.AppendLine($"  {kvp.Key}: {kvp.Value}");
            report.AppendLine("By form:");
            foreach (KeyValuePair<string, int> kvp in run.ByForm) report.AppendLine($"  {kvp.Key}: {kvp.Value}");
            if (run.SkippedMarker > 0) report.AppendLine($"Skipped {run.SkippedMarker} marker network(s)");
            if (run.SkippedNoWidth > 0) report.AppendLine($"Skipped {run.SkippedNoWidth} edge(s) with no usable width");
            if (run.SkippedDegenerate > 0) report.AppendLine($"Skipped {run.SkippedDegenerate} edge(s) whose centerline collapsed to a point");
            if (run.SkippedStale > 0) report.AppendLine($"Skipped {run.SkippedStale} edge(s) the simulation removed mid-rip");
            if (run.Skipped.Count > 0) report.AppendLine($"{run.Skipped.Count} surface(s) or texture(s) produced no material entry");
            if (!string.IsNullOrEmpty(materials)) report.AppendLine($"Materials: {materials}");
            report.AppendLine($"Output: {run.OutputDirectory}");

            // The conforming pass's heightmap copy (~33 MB) and per-piece bounds are only
            // needed while meshes build.
            _conformHeights = null;
            m_PieceHeightBounds.Clear();

            _log.Info(report.ToString());

            // A pipeline-driven run reports a short summary into the pipeline's combined dialog;
            // the full report is in the log either way.
            if (run.Completed != null)
            {
                string summary = $"Wrote {run.Writer?.Count ?? 0} segment(s) and {run.LaneWriter?.Count ?? 0} lane record(s), "
                               + $"{(run.Bytes + run.LaneBytes) / 1048576d:F1} MiB of glTF, in {run.Clock.Elapsed.TotalSeconds:F0} s.";
                try { run.Completed(summary); }
                catch (Exception ex) { _log.Warn($"Network rip completion callback failed: {ex}"); }
                return;
            }

            try
            {
                Game.UI.MessageDialog dialog = new("Options.SECTION[Carto.Carto.Mod]",
                                                   Settings.Fit(report.ToString()), "Common.OK");
                Instance.UI.appBindings.ShowMessageDialog(dialog, null);
            }
            catch (Exception ex)
            {
                _log.Warn($"Could not show the network rip result: {ex.Message}");
            }
        }

        // ====================================================================================
        // Lane-drawn geometry — hanging cables, fences, hedges (bundle layer `lanemeshes/`).
        //
        // ====================================================================================

        /// <summary>
        /// Record one lane's drawn geometry, if its prefab draws any, as a parameter record in
        /// <c>lanemeshes.jsonl</c> referencing the prefab's straight part meshes (contract §5B
        /// v2). The consumer bends; the algorithm is the contract's, reference-implemented in the
        /// Blender harness.
        /// The selection reproduces <c>BatchInstanceSystem.UpdateLaneInstances</c>: the sub-mesh
        /// test is the <b>inverted</b> one recorded in audit §12 — the accumulated flags are an
        /// exclusion mask, <c>(flags &amp; state) != 0 → skip</c> — with the per-lane bits (unsafe,
        /// level crossing, switch) read off the lane's own components. The record carries what
        /// <c>BatchDataSystem.UpdateLaneData</c> hands the vertex shader: the bézier's control
        /// points, the <c>CutRange</c> spans, the <c>NodeLane.m_WidthOffset</c> width scale, and
        /// the <c>HangingLane.m_Distances</c> end drops (the prefab-level
        /// <c>UtilityLaneData.m_Hanging</c> factor lives in the catalogue).
        /// Deliberate exclusions, each counted: tunnel-owned lanes here; <c>Pipeline</c>-layer and
        /// decal-flagged parts at the catalogue (they are properties of the part, not the lane).
        /// </summary>
        /// <summary>
        /// Whether a lane's owning net entity is underground — the game's
        /// <c>BatchInstanceSystem.IsNetOwnerTunnel</c>: the owner's own <c>Elevation</c>, or, for
        /// node owners (which carry none), the elevation of any edge connected to the node.
        /// </summary>
        private bool IsNetOwnerTunnel(Entity owner)
        {
            if (EntityManager.HasComponent<Game.Net.Elevation>(owner)
                && (math.cmin(EntityManager.GetComponentData<Game.Net.Elevation>(owner).m_Elevation) < 0f))
                return true;

            if (EntityManager.HasBuffer<Game.Net.ConnectedEdge>(owner))
            {
                DynamicBuffer<Game.Net.ConnectedEdge> edges = EntityManager.GetBuffer<Game.Net.ConnectedEdge>(owner, true);
                for (int i = 0; i < edges.Length; i++)
                {
                    Entity edge = edges[i].m_Edge;
                    if (EntityManager.HasComponent<Game.Net.Elevation>(edge)
                        && (math.cmin(EntityManager.GetComponentData<Game.Net.Elevation>(edge).m_Elevation) < 0f))
                        return true;
                }
            }

            return false;
        }

        /// <param name="run">The rip in flight.</param>
        /// <param name="entity">The lane to record.</param>
        private void RipLaneGeometry(NetworkRun run, Entity entity)
        {
            if (!EntityManager.Exists(entity))
            {
                run.SkippedLaneStale++;
                return;
            }

            Entity prefab = EntityManager.GetComponentData<PrefabRef>(entity).m_Prefab;
            if (prefab == Entity.Null) return;

            LanePrefabEntry entry = GetLanePrefab(run, prefab);
            if (entry.Parts.Count == 0) return;

            Curve curve = EntityManager.GetComponentData<Curve>(entity);
            if (!(curve.m_Length > 0.1f))
            {
                // The game's own gate (`UpdateLaneInstances`): a sub-decimetre lane draws nothing.
                //
                run.SkippedLaneDegenerate++;
                return;
            }

            Entity owner = Entity.Null;
            if (EntityManager.HasComponent<Game.Common.Owner>(entity))
                owner = EntityManager.GetComponentData<Game.Common.Owner>(entity).m_Owner;

            // A lane whose owning network runs below ground is drawn by the game on its Tunnel
            // layer — real geometry, visible whenever the cutaway shows it. The bundle renders
            // tunnels in full (the terrain cutout opens their portals), so these lanes are
            // included and tagged rather than skipped; a consumer that wants the surface world
            // only filters on the tag. The test is the game's `IsNetOwnerTunnel` in full: the
            // owner's own elevation, and — for node owners, which carry no elevation of their
            // own — every edge connected to the node.
            //
            bool tunnel = (owner != Entity.Null) && IsNetOwnerTunnel(owner);

            SubMeshFlags excluded = SubMeshFlags.RequireEditor
                | (Instance.City.leftHandTraffic ? SubMeshFlags.RequireRightHandTraffic
                                                 : SubMeshFlags.RequireLeftHandTraffic);

            if (EntityManager.HasComponent<Game.Net.PedestrianLane>(entity)
                && ((EntityManager.GetComponentData<Game.Net.PedestrianLane>(entity).m_Flags & PedestrianLaneFlags.Unsafe) != 0))
                excluded |= SubMeshFlags.RequireSafe;

            if (EntityManager.HasComponent<Game.Net.CarLane>(entity))
            {
                Game.Net.CarLane carLane = EntityManager.GetComponentData<Game.Net.CarLane>(entity);
                if ((carLane.m_Flags & CarLaneFlags.Unsafe) != 0) excluded |= SubMeshFlags.RequireSafe;
                if ((carLane.m_Flags & CarLaneFlags.LevelCrossing) == 0) excluded |= SubMeshFlags.RequireLevelCrossing;
            }

            if (EntityManager.HasComponent<Game.Net.TrackLane>(entity))
            {
                Game.Net.TrackLane trackLane = EntityManager.GetComponentData<Game.Net.TrackLane>(entity);
                if ((trackLane.m_Flags & TrackLaneFlags.LevelCrossing) == 0) excluded |= SubMeshFlags.RequireLevelCrossing;
                excluded |= ((trackLane.m_Flags & (TrackLaneFlags.Switch | TrackLaneFlags.DiamondCrossing)) == 0)
                          ? SubMeshFlags.RequireTrack : SubMeshFlags.RequireClear;
            }

            // The hanging drop is the game's cubic: ends are `HangingLane.m_Distances`, middle
            // handles `(distance + hanging × length) × ⅔` — the quadratic-to-cubic lift of a
            // parabola, wind sway omitted. The record ships the per-lane distances; the
            // prefab-level `m_Hanging` factor is in the catalogue, and the consumer builds the
            // cubic (contract §5B v2 documents the formula).
            //
            float2 hangDistances = float2.zero;
            if (EntityManager.HasComponent<HangingLane>(entity))
                hangDistances = EntityManager.GetComponentData<HangingLane>(entity).m_Distances;
            bool hasHang = (entry.Hanging != 0f) || math.any(hangDistances != 0f);

            // Node lanes carry a width offset where shared lane ends merge; the scale runs
            // start-to-end exactly as `BuildCurveScale(NodeLane, NetLaneData)` hands it over.
            //
            float2 widthScale = new(1f, 1f);
            if (EntityManager.HasComponent<NodeLane>(entity) && EntityManager.HasComponent<NetLaneData>(prefab))
            {
                NetLaneData laneData = EntityManager.GetComponentData<NetLaneData>(prefab);
                if (laneData.m_Width != 0f)
                    widthScale = 1f + (EntityManager.GetComponentData<NodeLane>(entity).m_WidthOffset / laneData.m_Width);
            }

            // The uncut spans of the curve, walked the way `UpdateLaneInstances` walks
            // `CutRange`s: a driveway through a fence, or a junction through a hedge, is a hole,
            // not an end. The game re-gates every span on the same 0.1 m draw threshold
            // (`curve3.m_Length > 0.1f` on the span's arc length), so sub-decimetre fragments
            // between two cuts draw nothing and are not recorded. A lane whose every span fails
            // draws nothing at all.
            //
            List<float2> spans = new();
            bool hasCuts = EntityManager.HasBuffer<CutRange>(entity);
            if (hasCuts)
            {
                DynamicBuffer<CutRange> cuts = EntityManager.GetBuffer<CutRange>(entity, true);
                float previous = 0f;
                for (int j = 0; j <= cuts.Length; j++)
                {
                    float min = (j < cuts.Length) ? cuts[j].m_CurveDelta.min : 1f;
                    float max = (j < cuts.Length) ? cuts[j].m_CurveDelta.max : 1f;
                    if ((min >= previous) && ((curve.m_Length * (min - previous)) > 0.1f))
                        spans.Add(new float2(previous, min));
                    previous = max;
                }

                if (spans.Count == 0)
                {
                    run.SkippedLaneDegenerate++;
                    return;
                }
            }

            LaneGeometryRecord record = new()
            {
                Id = entity.Index,
                Prefab = entry.Key,
                Category = entry.Category,
                CurveA = curve.m_Bezier.a,
                CurveB = curve.m_Bezier.b,
                CurveC = curve.m_Bezier.c,
                CurveD = curve.m_Bezier.d,
                Spans = spans,
                WidthScale = widthScale
            };

            // The per-lane part selection the game applies in `UpdateLaneInstances`, resolved by
            // the producer so a consumer never needs the flag semantics: a lane whose every part
            // is excluded draws nothing, exactly as in-game.
            //
            foreach (LanePartRef part in entry.Parts)
            {
                if ((part.Flags & excluded) == 0) record.Parts.Add(part.Index);
            }

            if (record.Parts.Count == 0)
            {
                run.SkippedLaneExcluded++;
                return;
            }

            if (owner != Entity.Null) record.Owner = owner.Index;

            if (tunnel)
            {
                record.Tunnel = true;
                run.LaneTunnel++;
            }

            // Road wear (audit P10): the serialized state behind the game's lane-decal
            // deterioration tint in the normal view — BatchDataSystem sets
            // `colossal_CurveDeterioration = LaneCondition.m_Wear / 10` per lane. Raw game value
            // (0..10), only when non-zero, to keep the layer lean. Not `NetCondition.m_Wear`,
            // which is infoview-only.
            //
            if (EntityManager.HasComponent<Game.Net.LaneCondition>(entity))
            {
                float wear = EntityManager.GetComponentData<Game.Net.LaneCondition>(entity).m_Wear;
                if (wear != 0f)
                {
                    record.Wear = wear;
                    run.LaneWorn++;
                }
            }

            if (hasHang)
            {
                record.HasHang = true;
                record.HangDistances = hangDistances;
                run.LaneHanging++;
            }

            // The lane's resolved paint, exactly as instances carry it (contract §7.2) — hedges
            // and fences run through the same MeshColor variation as props do.
            //
            if (EntityManager.HasBuffer<Game.Rendering.MeshColor>(entity))
            {
                DynamicBuffer<Game.Rendering.MeshColor> colors = EntityManager.GetBuffer<Game.Rendering.MeshColor>(entity, true);
                if (colors.Length > 0) record.ColorSet = InstanceRipSystem.ColorSetJson(colors[0].m_ColorSet);
            }

            run.LaneWriter.Write(record);
            run.LanesByCategory.TryGetValue(entry.Category, out int count);
            run.LanesByCategory[entry.Category] = count + 1;
        }

        /// <summary>
        /// Read a lane prefab's drawable parts once, through the same reader every building goes
        /// through, so their surfaces land in the same material table — write each distinct part
        /// mesh into <c>lanemeshes/</c> exactly once, and add the prefab's entry to the
        /// <c>laneprefabs.json</c> catalogue.
        /// </summary>
        /// <param name="run">The rip in flight.</param>
        /// <param name="prefab">The lane prefab entity.</param>
        /// <returns>The entry; its parts are empty when the prefab draws nothing.</returns>
        private LanePrefabEntry GetLanePrefab(NetworkRun run, Entity prefab)
        {
            if (run.LaneParts.TryGetValue(prefab, out LanePrefabEntry cached)) return cached;

            LanePrefabEntry entry = new();

            // Category and the hanging factor are prefab properties (`UtilityLaneData`), so they
            // live in the catalogue rather than in every record.
            //
            if (EntityManager.HasComponent<UtilityLaneData>(prefab))
            {
                UtilityLaneData utility = EntityManager.GetComponentData<UtilityLaneData>(prefab);

                if ((utility.m_UtilityTypes & (UtilityTypes.WaterPipe | UtilityTypes.SewagePipe | UtilityTypes.StormwaterPipe)) != 0)
                    entry.Category = "pipe";
                else if ((utility.m_UtilityTypes & (UtilityTypes.LowVoltageLine | UtilityTypes.HighVoltageLine | UtilityTypes.Catenary)) != 0)
                    entry.Category = "cable";
                else if ((utility.m_UtilityTypes & UtilityTypes.Fence) != 0)
                    entry.Category = "fence";

                entry.Hanging = utility.m_Hanging;
            }

            List<object> catalogueParts = new();

            if (EntityManager.HasBuffer<SubMesh>(prefab))
            {
                DynamicBuffer<SubMesh> buffer = EntityManager.GetBuffer<SubMesh>(prefab, true);

                // Copy out before reading geometry: obtaining a mesh loads an asset, and a
                // dynamic buffer is only valid until the entity's chunk moves.
                //
                SubMesh[] subMeshes = new SubMesh[buffer.Length];
                for (int i = 0; i < buffer.Length; i++) subMeshes[i] = buffer[i];

                foreach (SubMesh subMesh in subMeshes)
                {
                    Entity meshEntity = subMesh.m_SubMesh;
                    if ((meshEntity == Entity.Null) || !EntityManager.HasComponent<MeshData>(meshEntity)) continue;

                    MeshData meshData = EntityManager.GetComponentData<MeshData>(meshEntity);

                    // Parts whose default layers hold no world-view bit are never drawn in the
                    // world (`SearchSystem.GetLayers` hands `m_DefaultLayers` back verbatim
                    // except the exact Pipeline|SubPipeline pair, and `GetBoundsMask` counts
                    // only Default/Moving/Tunnel/Marker as `NormalLayers`) — underground pipes,
                    // cables and waterway overlays stay excluded. Tunnel-layer parts are world
                    // geometry — the game draws them on its Tunnel cutaway layer — and are
                    // kept, as the bundle renders tunnels in full. Decal-state
                    // parts are NOT excluded — they are how the game paints its junction
                    // interiors: `TerrainSystem` flattens the ground under a junction
                    // (`ShiftTerrain`/`ClipTerrain`) and the drive lanes crossing it carry
                    // decal sub-meshes that project asphalt and markings onto that ground. A
                    // bundle without them shows exactly the petal-shaped holes between the
                    // corner sweeps that three rounds of junction "fill" tried to invent
                    // geometry for. They join the catalogue tagged `decal`, and the consumer
                    // bends them like any part and lifts them off the surface.
                    //
                    bool decal = (meshData.m_State & MeshFlags.Decal) != 0;
                    if (decal)
                    {
                        run.SkippedLaneDecal++;

                        // The advanced toggle: markings and wear can be deselected outright, in
                        // which case the part never enters the catalogue — same shape as the
                        // pipeline-layer exclusion below.
                        if (!run.IncludeLaneDecals) continue;
                    }

                    const MeshLayer world = MeshLayer.Default | MeshLayer.Moving | MeshLayer.Tunnel | MeshLayer.Marker;
                    if ((meshData.m_DefaultLayers != 0) && ((meshData.m_DefaultLayers & world) == 0))
                    {
                        run.SkippedLanePipeline++;
                        continue;
                    }

                    if (!run.LaneMeshIds.TryGetValue(meshEntity, out string assetId))
                    {
                        string name = Instance.Name.GetPrefabName(meshEntity);
                        if (string.IsNullOrEmpty(name)) name = $"lane_mesh_{meshEntity.Index}";

                        // Unique over the whole run: two distinct mesh entities sharing a name
                        // must not share a file — the join key's uniqueness is assigned over the
                        // full set, never per name.
                        //
                        assetId = MeshRipSystem.SanitizeAssetId(name);
                        if (!run.LaneIdsUsed.Add(assetId))
                        {
                            assetId = $"{assetId}_{meshEntity.Index}";
                            run.LaneIdsUsed.Add(assetId);
                        }

                        MeshAsset mesh = Instance.MeshRip.ReadMesh(meshEntity, assetId, name);
                        if (mesh == null) continue;

                        run.LaneMeshIds[meshEntity] = assetId;
                        run.Queue.Add(new NetworkItem { Mesh = mesh, IsLane = true });
                    }

                    entry.Parts.Add(new LanePartRef { Flags = subMesh.m_Flags, Index = catalogueParts.Count });
                    Dictionary<string, object> cataloguePart;
                    catalogueParts.Add(cataloguePart = new Dictionary<string, object>
                    {
                        ["assetId"] = assetId,
                        ["pos"] = new[]
                        {
                            Math.Round((double)subMesh.m_Position.x, 4),
                            Math.Round((double)subMesh.m_Position.y, 4),
                            Math.Round((double)subMesh.m_Position.z, 4)
                        },
                        ["rot"] = new[]
                        {
                            Math.Round((double)subMesh.m_Rotation.value.x, 6),
                            Math.Round((double)subMesh.m_Rotation.value.y, 6),
                            Math.Round((double)subMesh.m_Rotation.value.z, 6),
                            Math.Round((double)subMesh.m_Rotation.value.w, 6)
                        },
                        ["inverted"] = (meshData.m_State & MeshFlags.Invert) != 0,
                        ["tilingCount"] = meshData.m_TilingCount,
                        ["geometryTiling"] = (meshData.m_State & MeshFlags.Tiling) != 0,
                        ["boundsMin"] = new[]
                        {
                            Math.Round((double)meshData.m_Bounds.min.x, 4),
                            Math.Round((double)meshData.m_Bounds.min.y, 4),
                            Math.Round((double)meshData.m_Bounds.min.z, 4)
                        },
                        ["boundsMax"] = new[]
                        {
                            Math.Round((double)meshData.m_Bounds.max.x, 4),
                            Math.Round((double)meshData.m_Bounds.max.y, 4),
                            Math.Round((double)meshData.m_Bounds.max.z, 4)
                        }
                    });

                    if (decal) cataloguePart["decal"] = true;
                }
            }

            if (entry.Parts.Count > 0)
            {
                string prefabName = Instance.Name.GetPrefabName(prefab);
                string key = MeshRipSystem.SanitizeAssetId(
                    string.IsNullOrEmpty(prefabName) ? $"lane_prefab_{prefab.Index}" : prefabName);
                if (run.LaneCatalogue.ContainsKey(key)) key = $"{key}_{prefab.Index}";

                entry.Key = key;
                run.LaneCatalogue[key] = new Dictionary<string, object>
                {
                    ["category"] = entry.Category,
                    ["hanging"] = Math.Round((double)entry.Hanging, 5),
                    ["parts"] = catalogueParts
                };
            }

            run.LaneParts[prefab] = entry;
            return entry;
        }


        /// <summary>
        /// Encode every queued texture and serialise every queued segment mesh, in the order the
        /// rip produced them, until it stops queueing.
        /// </summary>
        /// <param name="run">The rip in flight.</param>
        private static void Encode(NetworkRun run)
        {
            MaterialRipSystem materials = run.Materials;

            foreach (NetworkItem item in run.Queue.GetConsumingEnumerable())
            {
                // One bad item must not take the writer down with it: the queue would then never
                // drain, and the rip would block forever waiting for it.
                //
                try
                {
                    // Textures first, always: they arrive before the segment that named them, and
                    // encoding one is what gives it the content hash that segment's .glb writes down.
                    //
                    if (item.Texture != null)
                    {
                        materials.WriteTexture(item.Texture);
                        continue;
                    }

                    MeshAsset mesh = item.Mesh;
                    if (mesh == null) continue;

                    string path = IOUtils.CombinePath(item.IsLane ? run.LaneMeshDirectory : run.MeshDirectory,
                                                      $"{mesh.AssetId}.glb");
                    long written = GltfWriter.Write(path, mesh, materials.Describe);
                    if (item.IsLane) System.Threading.Interlocked.Add(ref run.LaneBytes, written);
                    else run.Bytes += written;
                }
                catch (Exception ex)
                {
                    _log.Warn($"Could not write a network {(item.Texture != null ? "texture" : "mesh")}: {ex.Message}");
                }
            }
        }

        /// <summary>
        /// Close the writer's queue, wait for it, and write <c>materials.json</c>.
        /// </summary>
        /// <param name="run">The run being finished or abandoned.</param>
        /// <returns>The material summary, or <c>null</c>.</returns>
        private string Drain(NetworkRun run)
        {
            try
            {
                run.Queue?.CompleteAdding();
                run.Encoder?.Wait();
            }
            catch (Exception ex)
            {
                _log.Warn($"Network writer ended with an error: {ex.Message}");
            }

            try
            {
                return Instance.MaterialRip.Finish(run.Report, run.Skipped);
            }
            catch (Exception ex)
            {
                _log.Error($"Material rip failed to finish: {ex}");
                return null;
            }
        }

        /// <summary>
        /// Assemble one network edge into a single mesh: the junction flare at its start, the run
        /// between the nodes, and the flare at its end.
        /// <c>Composition</c> names three composition entities and each has its own cross-section,
        /// because an intersection's surface is genuinely different geometry from the road leading
        /// into it. Assembling all three covers node to node with nothing left between them, which
        /// is what a constant-width ribbon could never do at a skewed junction.
        /// </summary>
        /// <param name="entity">The edge entity.</param>
        /// <param name="geometry">Its edge geometry.</param>
        /// <param name="center">The origin the mesh is built around.</param>
        /// <param name="assetId">The asset id to label it with.</param>
        /// <param name="cache">The piece mesh cache.</param>
        /// <param name="report">Where to note the working, or <c>null</c> to stay quiet.</param>
        /// <returns>The mesh, or <c>null</c> when the network has no pieces to assemble.</returns>
        private MeshAsset AssembleNetwork(Entity entity, EdgeGeometry geometry, float3 center, string assetId,
                                          Dictionary<Entity, MeshAsset> cache, StringBuilder report)
        {
            Composition parts = EntityManager.GetComponentData<Composition>(entity);

            List<float3> vertices = new();
            List<float2> uvs = new();
            List<int> indices = new();
            List<MeshPrimitive> primitives = new();

            // The game's own draw gates (`BatchInstanceSystem.UpdateNetInstances`): an edge part
            // needs more than 0.1 m of run, a flare more than 0.05 m on either half. Below that
            // the game draws nothing, and assembling it here would emit degenerate slivers the
            // game never shows. Geometry itself is the ported game generator
            // (NetworkRipSystem.GameMesh.cs): parameters exactly as `BatchDataHelpers` builds
            // them, vertices exactly as `GenerateCompositionMesh` maps them, evaluated on CPU.
            //
            if (EntityManager.HasComponent<StartNodeGeometry>(entity))
            {
                EdgeNodeGeometry node = EntityManager.GetComponentData<StartNodeGeometry>(entity).m_Geometry;
                if (math.any(node.m_Left.m_Length > 0.05f) | math.any(node.m_Right.m_Length > 0.05f))
                {
                    BuildNodeSide(parts.m_StartNode, node, center, "startNode",
                                  cache, vertices, uvs, indices, primitives, report);
                }
            }

            if (math.any((geometry.m_Start.m_Length + geometry.m_End.m_Length) > 0.1f)
                && (parts.m_Edge != Entity.Null)
                && EntityManager.HasComponent<NetCompositionMeshRef>(parts.m_Edge))
            {
                bool rotated = EntityManager.GetComponentData<NetCompositionMeshRef>(parts.m_Edge).m_Rotate;
                if (rotated) _rotatedEdges++;
                CompositionCurves curves = EdgeCurves(geometry, rotated);
                BuildGameComposition(parts.m_Edge, curves, center, "edge",
                                     cache, vertices, uvs, indices, primitives, report);
            }

            if (EntityManager.HasComponent<EndNodeGeometry>(entity))
            {
                EdgeNodeGeometry node = EntityManager.GetComponentData<EndNodeGeometry>(entity).m_Geometry;
                if (math.any(node.m_Left.m_Length > 0.05f) | math.any(node.m_Right.m_Length > 0.05f))
                {
                    BuildNodeSide(parts.m_EndNode, node, center, "endNode",
                                  cache, vertices, uvs, indices, primitives, report);
                }
            }

            // No junction patch of any kind: the arms' node meshes tile the interior themselves —
            // median pieces on the middle curve plus the zero-width intersection piece's
            // three-rail wedge (audit §18) — so a patch could only double geometry the mapping
            // already emits. The bespoke fan this once carried invented geometry the game does
            // not have, and shipped it wrongly shaded.
            //
            return Finish(assetId, vertices, uvs, indices, primitives);
        }

        /// <summary>
        /// Reduce a name to the character set the contract allows an <c>assetId</c>.
        /// </summary>
        /// <param name="name">The raw name.</param>
        /// <returns>A safe id.</returns>
        private static string SanitizeId(string name)
        {
            if (string.IsNullOrEmpty(name)) return "unnamed";

            StringBuilder safe = new(name.Length);
            foreach (char c in name)
            {
                safe.Append(char.IsLetterOrDigit(c) || (c == '.') || (c == '-') || (c == '_') ? c : '_');
            }

            // The pattern requires the first character to be alphanumeric.
            //
            if (!char.IsLetterOrDigit(safe[0])) safe.Insert(0, 'x');
            return safe.ToString();
        }

        /// <summary>
        /// Whether an edge is the invisible simulation furniture both rip queries drop — a pipe or
        /// cable junction anchor, or airport airspace.
        /// Taxiways carry the marker component and are genuinely drawn, which is why they are the
        /// one exception, exactly as the vector export has it.
        /// </summary>
        /// <param name="entity">The edge entity.</param>
        /// <returns>Whether it is a marker network.</returns>
        private bool IsMarkerNetwork(Entity entity)
        {
            if (!EntityManager.HasComponent<Composition>(entity)) return false;

            Entity edgeComposition = EntityManager.GetComponentData<Composition>(entity).m_Edge;
            bool isTaxiway = (edgeComposition != Entity.Null)
                          && EntityManager.HasComponent<TaxiwayComposition>(edgeComposition);

            if (EntityManager.HasComponent<Game.Net.Marker>(entity) && !isTaxiway) return true;

            return isTaxiway
                && ((EntityManager.GetComponentData<TaxiwayComposition>(edgeComposition).m_Flags
                     & TaxiwayFlags.Airspace) != 0);
        }

        /// <summary>
        /// How many edges meet at a node. Three or more makes it an intersection rather than a
        /// bend or a dead end.
        /// </summary>
        /// <param name="node">The node entity.</param>
        /// <returns>The number of connected edges.</returns>
        private int CountConnections(Entity node)
        {
            if ((node == Entity.Null) || !EntityManager.HasBuffer<ConnectedEdge>(node)) return 0;
            return EntityManager.GetBuffer<ConnectedEdge>(node, true).Length;
        }



        /// <summary>
        /// The across-width vertex remap CS2 applies to a junction flare.
        /// A composition names four positions across each half of its cross-section
        /// (<c>NetCompositionData.m_SyncVertexOffsets*</c>), and a node geometry names where those
        /// four have to end up in this particular junction
        /// (<c>EdgeNodeGeometry.m_SyncVertexTargets*</c>). The game hands both to the vertex shader
        /// as <c>m_CompositionSync0..3</c> and lets it move each vertex across the width to match —
        /// which is how a lane edge still lines up with the lane it meets when four roads of
        /// different widths share a junction.
        /// The knots are measured per half, from the outer edge to the median, which is the
        /// coordinate the assembly's own <c>s</c> already runs in — <c>CalculateSyncVertexOffsets</c>
        /// normalises by <c>(x - middleOffset) / (width / 2)</c>, and every real composition
        /// measured has <c>middleOffset</c> zero. Both outermost knots are fixed points in the
        /// measured data, so this moves lane boundaries within a flare and never its outer kerb or
        /// its median: it is not what closes a junction, it is what stops the pieces inside one
        /// from stepping.
        /// The interpolation between knots is the shader's, and CS2 ships shaders compiled inside
        /// asset bundles, so it is read here as piecewise linear — the reading the measured knots
        /// support and the only one that keeps every knot exactly on its target. Outside the
        /// outermost knots the shift is held constant rather than extrapolated, so a composition
        /// whose knots do not span the full half cannot throw a vertex past the kerb.
        /// </summary>
        private readonly struct VertexSync
        {
            private readonly float4 m_OffsetsLeft, m_TargetsLeft, m_OffsetsRight, m_TargetsRight;
            private readonly bool m_Active;

            /// <summary>No remap — what an edge, and any composition without sync data, gets.
            ///</summary>
            public static VertexSync None => default;

            public VertexSync(NetCompositionData composition, EdgeNodeGeometry node)
            {
                m_OffsetsLeft = composition.m_SyncVertexOffsetsLeft;
                m_TargetsLeft = node.m_SyncVertexTargetsLeft;
                m_OffsetsRight = composition.m_SyncVertexOffsetsRight;
                m_TargetsRight = node.m_SyncVertexTargetsRight;

                // An unset target arrives as NaN, and one NaN would propagate into every vertex of
                // the flare. Where the two agree there is nothing to do anyway, so treat that as
                // inactive too and keep the cost off the ordinary node.
                //
                m_Active = !math.any(math.isnan(m_OffsetsLeft)) && !math.any(math.isnan(m_TargetsLeft))
                        && !math.any(math.isnan(m_OffsetsRight)) && !math.any(math.isnan(m_TargetsRight))
                        && (math.any(m_OffsetsLeft != m_TargetsLeft)
                            || math.any(m_OffsetsRight != m_TargetsRight));
            }

            /// <summary>
            /// Move one across-half position from where the cross-section authored it to where this
            /// junction needs it.
            /// Each half's knots live in that half's own <c>xParam</c> coordinate — left: 0 at the
            /// outer edge, 1 at the middle; right: 0 at the middle, 1 at the outer edge. That is
            /// the coordinate `GeometrySystem` builds them in: the twin conversion is
            /// `offsetsRight = 1 − offsetsLeft.wzyx` (line 2603) and
            /// `CalculateVertexSyncTarget`'s right branch anchors on `1 − a.w` (the outer-right
            /// margin), returning targets ascending toward the outer edge. No flip is applied
            /// here — an earlier revision flipped the right half through <c>1 − s</c>, which
            /// dragged every right-side curb knot to a mirrored position and jutted kerbs into
            /// the roadway at junction flares.
            /// </summary>
            /// <param name="s">The position across this half, in the half's own coordinate.
            ///</param>
            /// <param name="leftHalf">Whether this is the left half.</param>
            /// <returns>The remapped position.</returns>
            public float Apply(float s, bool leftHalf)
            {
                if (!m_Active) return s;
                return leftHalf ? Remap(s, m_OffsetsLeft, m_TargetsLeft)
                                : Remap(s, m_OffsetsRight, m_TargetsRight);
            }

            // The end regions scale with pinned endpoints (0 → 0, 1 → 1) rather than translate:
            // the flare's boundary curves were already moved to their targets when
            // `CalculateVertexSyncTarget` mutated the node geometry (`m_Left/m_Right.c/d`), so
            // the vertex riding the boundary at s = 0 must stay on it; a translation shears the
            // outer strip — the curb row — off the boundary the game keeps it on.
            //
            private static float Remap(float s, float4 o, float4 t)
            {
                if (s <= o.x) return Between(s, 0f, o.x, 0f, t.x);
                if (s <= o.y) return Between(s, o.x, o.y, t.x, t.y);
                if (s <= o.z) return Between(s, o.y, o.z, t.y, t.z);
                if (s <= o.w) return Between(s, o.z, o.w, t.z, t.w);
                return Between(s, o.w, 1f, t.w, 1f);
            }

            // Two knots at the same offset are a collapsed interval, not a slope; snapping to the
            // far target keeps the map monotone instead of dividing by zero.
            //
            private static float Between(float s, float o0, float o1, float t0, float t1)
                => ((o1 - o0) > 1e-6f) ? math.lerp(t0, t1, (s - o0) / (o1 - o0)) : t1;
        }

        /// <summary>
        /// Finish a shared mesh: pack the accumulated lists and rebuild normals.
        /// </summary>
        /// <param name="assetId">The asset id to label it with.</param>
        /// <param name="vertices">The accumulated vertices.</param>
        /// <param name="uvs">The accumulated UVs.</param>
        /// <param name="indices">The accumulated indices.</param>
        /// <param name="primitives">The accumulated primitives.</param>
        /// <returns>The mesh, or <c>null</c> when nothing was assembled.</returns>
        private static MeshAsset Finish(string assetId, List<float3> vertices, List<float2> uvs,
                                        List<int> indices, List<MeshPrimitive> primitives)
        {
            if (vertices.Count == 0) return null;

            MeshAsset mesh = new()
            {
                AssetId = assetId,
                SourceName = assetId,
                Vertices = vertices.ToArray(),
                Uvs = uvs.ToArray(),
                Indices = indices.ToArray(),
                Primitives = primitives
            };

            // Normals have to be rebuilt, not carried over: bending the mesh rotates every face,
            // and a piece's authored normal points wherever the straight tile faced.
            //
            mesh.Normals = BuildNormals(mesh.Vertices, mesh.Indices);
            return mesh;
        }

        /// <summary>
        /// Rebuild vertex normals by averaging the faces that share each vertex.
        /// </summary>
        /// <param name="vertices">The positions.</param>
        /// <param name="indices">The triangle list.</param>
        /// <returns>One normal per vertex.</returns>
        private static float3[] BuildNormals(float3[] vertices, int[] indices)
        {
            float3[] normals = new float3[vertices.Length];

            for (int i = 0; i + 2 < indices.Length; i += 3)
            {
                int a = indices[i], b = indices[i + 1], c = indices[i + 2];
                float3 face = math.cross(vertices[b] - vertices[a], vertices[c] - vertices[a]);
                normals[a] += face;
                normals[b] += face;
                normals[c] += face;
            }

            for (int i = 0; i < normals.Length; i++)
            {
                float length = math.length(normals[i]);
                normals[i] = (length > 1e-9f) ? (normals[i] / length) : new float3(0f, 1f, 0f);
            }

            return normals;
        }
        /// <summary>
        /// Build the world-space centerline of one edge, from its start node to its end node.
        /// The two halves of <see cref="EdgeGeometry"/> give the road surface's left and right
        /// bezier. Bezier evaluation is linear in the control points, so averaging the control
        /// points of the two produces exactly the pointwise midline — no sampling error, and the
        /// existing straightness test still applies to it.
        /// The result is then extended to the two node positions, so a junction is closed by the
        /// segments meeting in it rather than left as a hole.
        /// </summary>
        /// <param name="entity">The edge entity.</param>
        /// <param name="edge">Its <see cref="Edge"/> component.</param>
        /// <param name="geometry">Its <see cref="EdgeGeometry"/> component.</param>
        /// <returns>The tessellated polyline.</returns>
        private List<float3> BuildCenterline(Entity entity, Edge edge, EdgeGeometry geometry)
        {
            List<float3> points = new();

            Tessellate(Midline(geometry.m_Start), points);
            Tessellate(Midline(geometry.m_End), points);

            // A pipe or a power line has no road surface, so its `EdgeGeometry` is empty and the
            // midline collapses. Its `Curve` is still the run itself — every edge has one — so
            // falling back to it keeps utility networks in the bundle as the lines they are,
            // rather than dropping a whole category for want of a surface.
            //
            if ((points.Count < 2) && EntityManager.HasComponent<Curve>(entity))
            {
                points.Clear();
                Tessellate(EntityManager.GetComponentData<Curve>(entity).m_Bezier, points);
            }

            if (points.Count < 2) return points;

            bool hasStart = EntityManager.HasComponent<Node>(edge.m_Start);
            bool hasEnd = EntityManager.HasComponent<Node>(edge.m_End);
            float3 startPosition = hasStart ? EntityManager.GetComponentData<Node>(edge.m_Start).m_Position : default;
            float3 endPosition = hasEnd ? EntityManager.GetComponentData<Node>(edge.m_End).m_Position : default;

            // `EdgeGeometry.m_Start` is documented as the half nearest the start node, but an
            // inverted composition is a real state in CS2 and a reversed centerline would put the
            // segment's `startNode` end at the wrong junction. Comparing both endpoints against the
            // start node settles it for two lines and no assumptions.
            //
            if (hasStart && hasEnd
                && (math.distancesq(points[0], startPosition) > math.distancesq(points[points.Count - 1], startPosition)))
            {
                points.Reverse();
            }

            if (hasStart) Prepend(points, startPosition);
            if (hasEnd) Append(points, endPosition);

            return points;
        }

        /// <summary>
        /// The pointwise midline of a network segment's left and right boundary curves.
        /// </summary>
        /// <param name="segment">The boundary pair.</param>
        /// <returns>The midline bezier.</returns>
        private static Bezier4x3 Midline(Segment segment) => new(
            (segment.m_Left.a + segment.m_Right.a) * 0.5f,
            (segment.m_Left.b + segment.m_Right.b) * 0.5f,
            (segment.m_Left.c + segment.m_Right.c) * 0.5f,
            (segment.m_Left.d + segment.m_Right.d) * 0.5f);

        /// <summary>
        /// Append a bezier's points to a polyline, skipping duplicates at the join.
        /// </summary>
        /// <param name="curve">The curve to tessellate.</param>
        /// <param name="points">The polyline being built.</param>
        private static void Tessellate(Bezier4x3 curve, List<float3> points)
        {
            if (Utils.MathUtils.IsStraightLine(curve, StraightThreshold))
            {
                Append(points, curve.a);
                Append(points, curve.d);
                return;
            }

            int sections = (int)math.ceil(Colossal.Mathematics.MathUtils.Length(curve) / TessellationGap);
            if (sections < 1) sections = 1;

            for (int i = 0; i <= sections; i++)
            {
                Append(points, Colossal.Mathematics.MathUtils.Position(curve, (float)i / sections));
            }
        }

        /// <summary>
        /// Add a point unless it repeats the last one.
        /// The halves of an edge share an endpoint and a straight curve repeats its own, so
        /// without this every centerline would carry duplicate vertices — which a consumer
        /// extruding a ribbon turns into zero-length quads.
        /// </summary>
        /// <param name="points">The polyline being built.</param>
        /// <param name="point">The candidate point.</param>
        private static void Append(List<float3> points, float3 point)
        {
            if ((points.Count > 0) && (math.distancesq(points[points.Count - 1], point) < 1e-6f)) return;
            points.Add(point);
        }

        /// <summary>
        /// Add a point at the front unless it repeats the first one.
        /// </summary>
        /// <param name="points">The polyline being built.</param>
        /// <param name="point">The candidate point.</param>
        private static void Prepend(List<float3> points, float3 point)
        {
            if ((points.Count > 0) && (math.distancesq(points[0], point) < 1e-6f)) return;
            points.Insert(0, point);
        }

        /// <summary>
        /// The total width to extrude the centerline by, in metres.
        /// <see cref="NetCompositionData.m_Width"/> is the nominal width the game itself lays the
        /// composition out to, so it is preferred; measuring the surface boundary is the fallback
        /// for compositions that do not carry it.
        /// </summary>
        /// <param name="edgeComposition">The edge composition entity.</param>
        /// <param name="entity">The edge entity.</param>
        /// <param name="geometry">The edge geometry.</param>
        /// <returns>The width, or zero when none can be established.</returns>
        private float GetWidth(Entity edgeComposition, Entity entity, EdgeGeometry geometry)
        {
            if ((edgeComposition != Entity.Null) && EntityManager.HasComponent<NetCompositionData>(edgeComposition))
            {
                float width = EntityManager.GetComponentData<NetCompositionData>(edgeComposition).m_Width;
                if (width > 0f) return width;
            }

            float measured = math.max(math.distance(geometry.m_Start.m_Left.a, geometry.m_Start.m_Right.a),
                                      math.distance(geometry.m_End.m_Left.d, geometry.m_End.m_Right.d));
            if (measured > 0f) return measured;

            Entity prefab = EntityManager.GetComponentData<PrefabRef>(entity).m_Prefab;
            if ((prefab != Entity.Null) && EntityManager.HasComponent<NetGeometryData>(prefab))
                return EntityManager.GetComponentData<NetGeometryData>(prefab).m_DefaultWidth;

            return 0f;
        }

        /// <summary>
        /// Attach the contract's network attributes.
        /// </summary>
        /// <param name="entity">The edge entity.</param>
        /// <param name="edgeComposition">The edge composition entity.</param>
        /// <param name="width">The width already established.</param>
        /// <param name="record">The record to populate.</param>
        /// <param name="aggregateNames">The cache of resolved road names.</param>
        private void AddAttributes(Entity entity, Entity edgeComposition, float width, NetworkRecord record,
                                   Dictionary<Entity, string> aggregateNames)
        {
            Entity prefab = EntityManager.GetComponentData<PrefabRef>(entity).m_Prefab;

            string asset = Instance.Name.GetPrefabName(prefab);
            if (!string.IsNullOrEmpty(asset)) record.Attributes["asset"] = asset;

            // A road's name lives on the aggregate that groups its edges, not on the edge, and
            // resolving one goes through the game's localised name system. A city has far fewer
            // aggregates than edges, so the result is cached per aggregate.
            //
            if (EntityManager.HasComponent<Aggregated>(entity))
            {
                Entity aggregate = EntityManager.GetComponentData<Aggregated>(entity).m_Aggregate;
                if (aggregate != Entity.Null)
                {
                    if (!aggregateNames.TryGetValue(aggregate, out string name))
                    {
                        name = ResolveName(aggregate);
                        aggregateNames[aggregate] = name;
                    }

                    if (!string.IsNullOrEmpty(name)) record.Attributes["name"] = name;
                }
            }

            record.Attributes["category"] = GetCategory(prefab, edgeComposition);

            string form = "normal";
            string direction = "unknown";
            float limit = 0f;

            if (edgeComposition != Entity.Null)
            {
                if (EntityManager.HasComponent<NetCompositionData>(edgeComposition))
                {
                    NetCompositionData compositionData = EntityManager.GetComponentData<NetCompositionData>(edgeComposition);

                    CompositionFlags.General general = compositionData.m_Flags.m_General;
                    if ((general & CompositionFlags.General.Elevated) != 0) form = "elevated";
                    if ((general & CompositionFlags.General.Tunnel) != 0) form = "tunnel";

                    // The contract's fourth form, `bridge`, has no CS2 counterpart: the game
                    // elevates a road and lets the terrain and water decide what that looks like.
                    // A consumer that wants bridges reads `elevated` against the Phase 6 water
                    // raster; inventing the distinction here would be a guess.
                    //

                    CompositionState state = compositionData.m_State;
                    bool forward = ((state & CompositionState.HasForwardRoadLanes) != 0)
                                || ((state & CompositionState.HasForwardTrackLanes) != 0);
                    bool backward = ((state & CompositionState.HasBackwardRoadLanes) != 0)
                                 || ((state & CompositionState.HasBackwardTrackLanes) != 0);
                    if (forward && backward) direction = "twoway";
                    else if (forward || backward) direction = "oneway";
                }

                if (EntityManager.HasBuffer<NetCompositionLane>(edgeComposition))
                {
                    DynamicBuffer<NetCompositionLane> lanes = EntityManager.GetBuffer<NetCompositionLane>(edgeComposition, true);
                    int count = 0;

                    for (int i = 0; i < lanes.Length; i++)
                    {
                        LaneFlags flags = lanes[i].m_Flags;

                        // Road and track lanes are the ones a consumer means by "lanes"; the
                        // master lane is the group's stand-in rather than a lane of its own, and
                        // counting it would inflate every multi-lane road by one.
                        //
                        if ((((flags & LaneFlags.Road) != 0) || ((flags & LaneFlags.Track) != 0))
                            && ((flags & LaneFlags.Master) == 0)) count++;
                    }

                    record.Attributes["lanes"] = count;
                }

                limit = GetSpeedLimit(edgeComposition);
            }

            record.Attributes["form"] = form;
            record.Attributes["direction"] = direction;
            if (limit > 0f) record.Attributes["limit"] = Math.Round((double)limit, 1);

            if (EntityManager.HasComponent<Curve>(entity))
                record.Attributes["length"] = Math.Round((double)EntityManager.GetComponentData<Curve>(entity).m_Length, 3);

            // Also in `attrs`, as the contract's own example has it: the top-level `width` is the
            // geometry a consumer extrudes by, the attribute is the semantic road width, and the
            // two coincide in the centerline form.
            //
            record.Attributes["width"] = Math.Round((double)width, 3);

            // CS2 stores an elevation per end, not per segment, and a segment that climbs from the
            // ground onto a viaduct is exactly where that matters. The mean is kept because the
            // contract already names `elevation` and a consumer reading only it must keep working,
            // but both ends are published alongside: a segment running 0 m to 12 m and one sitting
            // flat at 6 m are the same number and completely different roads, and it is the
            // sloping ones a consumer has to cut terrain for or bridge.
            //
            if (EntityManager.HasComponent<Game.Net.Elevation>(entity))
            {
                float2 elevation = EntityManager.GetComponentData<Game.Net.Elevation>(entity).m_Elevation;
                record.Attributes["elevation"] = Math.Round((double)((elevation.x + elevation.y) * 0.5f), 3);
                record.Attributes["elevationStart"] = Math.Round((double)elevation.x, 3);
                record.Attributes["elevationEnd"] = Math.Round((double)elevation.y, 3);
            }
        }

        /// <summary>
        /// The displayable name of a road aggregate, or an empty string when it has none.
        /// The game's label name is not always a name: an unnamed road hands back the locale key
        /// its UI would look up, such as <c>Assets.NAME[Medium Road]</c>. Writing that into the
        /// bundle would hand a consumer a string from CS2's localisation system and call it a
        /// street name, so a key is resolved through the active dictionary and dropped when it
        /// resolves to nothing but itself — an unnamed road is simply unnamed.
        /// </summary>
        /// <param name="aggregate">The aggregate entity.</param>
        /// <returns>The name, or an empty string.</returns>
        private static string ResolveName(Entity aggregate)
        {
            string label = Instance.Name.GetLabelName(aggregate);
            if (string.IsNullOrEmpty(label)) return string.Empty;

            // A locale key, not a name — `Namespace.SECTION[Value]`.
            //
            if (label.IndexOf('[') < 0) return label;

            return LocaleUtils.TryTranslate(label, out string translated) ? translated : string.Empty;
        }

        /// <summary>
        /// Classify a network into a coarse, engine-neutral category name.
        /// Read off the composition's own components rather than the lane make-up: a composition
        /// that carries <c>RoadComposition</c> is a road because the game says so, which survives
        /// modded networks that the vector export's lane-prefab table has never seen.
        /// </summary>
        /// <param name="prefab">The net prefab entity.</param>
        /// <param name="edgeComposition">The edge composition entity.</param>
        /// <returns>The category name.</returns>
        private string GetCategory(Entity prefab, Entity edgeComposition)
        {
            if (edgeComposition != Entity.Null)
            {
                if (EntityManager.HasComponent<TaxiwayComposition>(edgeComposition))
                {
                    TaxiwayComposition taxiway = EntityManager.GetComponentData<TaxiwayComposition>(edgeComposition);
                    return ((taxiway.m_Flags & TaxiwayFlags.Runway) != 0) ? "runway" : "taxiway";
                }

                if (EntityManager.HasComponent<TrackComposition>(edgeComposition))
                {
                    TrackTypes trackType = EntityManager.GetComponentData<TrackComposition>(edgeComposition).m_TrackType;
                    if ((trackType & TrackTypes.Train) != 0) return "train";
                    if ((trackType & TrackTypes.Tram) != 0) return "tram";
                    if ((trackType & TrackTypes.Subway) != 0) return "subway";
                    return "track";
                }

                if (EntityManager.HasComponent<RoadComposition>(edgeComposition))
                {
                    RoadComposition road = EntityManager.GetComponentData<RoadComposition>(edgeComposition);
                    return ((road.m_Flags & Game.Prefabs.RoadFlags.UseHighwayRules) != 0) ? "highway" : "road";
                }

                if (EntityManager.HasComponent<WaterwayComposition>(edgeComposition)) return "waterway";
                if (EntityManager.HasComponent<PathwayComposition>(edgeComposition)) return "pathway";
            }

            if (prefab != Entity.Null)
            {
                if (EntityManager.HasComponent<PipelineData>(prefab)) return "pipe";
                if (EntityManager.HasComponent<PowerLineData>(prefab)) return "cable";
                if (EntityManager.HasComponent<FenceData>(prefab)) return "fence";
            }

            return "other";
        }

        /// <summary>
        /// The composition's speed limit in km/h, or zero when it declares none.
        /// CS2 stores speed in its own simulation unit; the vector export's 1.8 factor converts it
        /// to km/h and is reused here so both layers of a bundle quote the same number.
        /// </summary>
        /// <param name="edgeComposition">The edge composition entity.</param>
        /// <returns>The speed limit.</returns>
        private float GetSpeedLimit(Entity edgeComposition)
        {
            // The same precedence the vector export uses when a composition carries several:
            // pathway < waterway < taxiway < track < road.
            //
            float limit = 0f;

            if (EntityManager.HasComponent<PathwayComposition>(edgeComposition))
                limit = EntityManager.GetComponentData<PathwayComposition>(edgeComposition).m_SpeedLimit;
            if (EntityManager.HasComponent<WaterwayComposition>(edgeComposition))
                limit = EntityManager.GetComponentData<WaterwayComposition>(edgeComposition).m_SpeedLimit;
            if (EntityManager.HasComponent<TaxiwayComposition>(edgeComposition))
                limit = EntityManager.GetComponentData<TaxiwayComposition>(edgeComposition).m_SpeedLimit;
            if (EntityManager.HasComponent<TrackComposition>(edgeComposition))
                limit = EntityManager.GetComponentData<TrackComposition>(edgeComposition).m_SpeedLimit;
            if (EntityManager.HasComponent<RoadComposition>(edgeComposition))
                limit = EntityManager.GetComponentData<RoadComposition>(edgeComposition).m_SpeedLimit;

            return limit * 1.8f;
        }
    }
