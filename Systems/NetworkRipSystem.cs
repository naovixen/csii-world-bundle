    /// <summary>
    /// The system that writes every road, rail, path and utility run into <c>networks.jsonl</c>
    /// (PLAN Phase 5).
    /// <b>Two geometry forms, and where each comes from.</b> CS2 stores no per-segment road mesh.
    /// A composition names a cross-section — a <c>NetCompositionPiece</c> buffer of carriageway,
    /// shoulder, kerb and side pieces, each an ordinary <c>NetPiecePrefab</c> (which derives from
    /// <c>RenderPrefab</c>, so its geometry reads through the same route as a building's). The
    /// game tiles those pieces along the edge and bends them onto the road surface in the
    /// <i>vertex shader</i>, from the eight <c>CompositionMatrix</c> values
    /// <c>BatchDataHelpers.CalculateEdgeParameters</c> writes per instance — and
    /// <c>BuildEdgeMatrix</c> shows each of those is nothing but a bezier's four control points.
    /// For an edge they are precisely <see cref="EdgeGeometry"/>'s four boundary curves.
    /// So both forms come off the same CPU-side data. <see cref="RipNetworks"/> writes the
    /// centerline form — the midline of the left and right boundary curves, which is exact and
    /// cheap, and the mesh form — the pieces assembled and bent into real geometry, which is
    /// what carries a road's thickness, shoulders, kerbs and materials. Which one a network gets
    /// depends on whether it has a cross-section to assemble at all.
    /// <b>No <c>kind: "node"</c> records.</b> CS2 keeps no junction geometry on the node. The node
    /// entity carries <c>Game.Net.NodeGeometry</c>, and that is bounds, height, flatness and an
    /// offset — no surface at all; the flare where an edge meets an intersection is stored on the
    /// <i>edge</i>, as <c>StartNodeGeometry</c> / <c>EndNodeGeometry</c>. Emitting node records
    /// would invent geometry the game does not have.
    /// A node holding no geometry does <i>not</i> make a junction the union of the segment ends
    /// meeting in it: the flares part, and what closes the interior is each arm's own node mesh
    /// tiling its sector to the junction centre — median pieces riding <c>m_Middle</c>, and the
    /// zero-width <c>* Intersection Piece 0</c> every node composition carries mapped as a
    /// three-rail surface across the centre wedge (contract §5.1; the mapping subtlety and the
    /// bug it hid are <c>docs/cs2-api-audit.md</c> §18). The §5B <c>decal</c> parts over it are
    /// wear tint and markings, not the surface; the flattened ground beneath is the Phase 6
    /// terrain layer. Node meshes are generated by the ported game pipeline
    /// (<c>NetworkRipSystem.GameMesh.cs</c>); §16–§18 record what every earlier reconstruction
    /// got wrong.
    /// </summary>
    public partial class NetworkRipSystem : GameSystemBase
    {
        /// <summary>
        /// Mod's logger.
        /// See <see cref="Instance.Log"/> for more information.
        /// </summary>
        static readonly ILog _log = Instance.Log;

        /// <summary>
        /// The distance a bezier may deviate from its chord and still be written as a straight
        /// line, in metres.
        /// Tighter than the vector export's 1 m, because a road ribbon is looked at from close up
        /// rather than plotted on a map; a straight road still collapses to its two end points.
        /// </summary>
        private const float StraightThreshold = 0.2f;

        /// <summary>
        /// The spacing between tessellated points on a curved centerline, in metres.
        /// </summary>
        private const float TessellationGap = 3f;

        /// <summary>
        /// The query for placed network edges.
        /// </summary>
        EntityQuery _edgeQuery;

        /// <summary>
        /// The query for orphan nodes — a placed node no edge connects to, which the game draws
        /// as two half-disc caps (<c>NetSubMesh.Orphan1/2</c> via <c>CalculateOrphanParameters</c>).
        /// A rip that only walks edges misses them entirely.
        /// </summary>
        EntityQuery _orphanQuery;

        /// <summary>
        /// The query for placed lanes, for the lane-geometry stage. Broad on purpose — the stage
        /// itself skips lanes whose prefab draws nothing, which is nearly all of them.
        /// </summary>
        EntityQuery _laneQuery;


        /// <summary>
        /// How often the game rules this rip reproduces or defers were actually met — the
        /// validation matrix's live side. Rotated edges are reproduced; the rest are counted so a
        /// gap is a number in the report, not a surprise in a consumer.
        /// </summary>
        private int _rotatedEdges;
        private int _roundaboutParts;
        private int _skipBottomPieces;
        private int _railPieces;
        private int _emptyPieces;

        /// <summary>
        /// Piece placements whose render-cache buffers were absent and whose geometry was read
        /// from the asset instead (§42.6), and the distinct pieces that needed it.
        /// </summary>
        private int _piecesFromAsset;
        private readonly SortedSet<string> _pieceFromAssetNames = new();
        private readonly SortedSet<string> _emptyPieceNames = new();
        private int _orphanCaps;
        private int _pipelineCompositions;
        private int _lowerBottomPieces;
        private int _raiseTopPieces;
        private int _conformLoweredVerts;
        private int _conformKeptVerts;
        private int _conformRaisedVerts;
        private int _conformOutOfWindowTris;
        private int _unconformedPieces;
        private int _elevatedUnconformedPieces;
        private int _smoothTopPieces;
        private int _smoothTopVerts;
        private int _authoredFramePieces;
        private int _rebuiltFramePieces;
        private int _pinnedFrameVerts;

        /// <summary>
        /// The event triggered when the system instance is created.
        /// </summary>
        protected override void OnCreate()
        {
            _edgeQuery = GetEntityQuery(new EntityQueryDesc()
            {
                All = new ComponentType[]
                {
                    ComponentType.ReadOnly<Composition>(),
                    ComponentType.ReadOnly<Curve>(),
                    ComponentType.ReadOnly<Edge>(),
                    ComponentType.ReadOnly<EdgeGeometry>(),
                    ComponentType.ReadOnly<PrefabRef>()
                },
                None = new ComponentType[]
                {
                    // Mid-edit bookkeeping that must never reach the bundle, exactly as the
                    // instance rip excludes it.
                    //
                    ComponentType.ReadOnly<Game.Common.Deleted>(),
                    ComponentType.ReadOnly<Game.Tools.Temp>()
                }
            });

            _orphanQuery = GetEntityQuery(new EntityQueryDesc()
            {
                All = new ComponentType[]
                {
                    ComponentType.ReadOnly<Game.Net.Orphan>(),
                    ComponentType.ReadOnly<Node>(),
                    ComponentType.ReadOnly<PrefabRef>()
                },
                None = new ComponentType[]
                {
                    // The game's own exclusions: outside connections draw no orphan caps, and the
                    // usual mid-edit bookkeeping never reaches the bundle.
                    //
                    ComponentType.ReadOnly<Game.Net.OutsideConnection>(),
                    ComponentType.ReadOnly<Game.Common.Deleted>(),
                    ComponentType.ReadOnly<Game.Tools.Temp>()
                }
            });

            _laneQuery = GetEntityQuery(new EntityQueryDesc()
            {
                All = new ComponentType[]
                {
                    ComponentType.ReadOnly<Game.Net.Lane>(),
                    ComponentType.ReadOnly<Curve>(),
                    ComponentType.ReadOnly<PrefabRef>()
                },
                None = new ComponentType[]
                {
                    ComponentType.ReadOnly<Game.Common.Deleted>(),
                    ComponentType.ReadOnly<Game.Tools.Temp>(),
                    ComponentType.ReadOnly<Game.Tools.Hidden>()
                }
            });

            base.OnCreate();
            _log.Debug("NetworkRipSystem instance created.");
        }


        /// <summary>
        /// How many read-back textures and assembled segment meshes may wait to be written.
        /// Each holds a full uncompressed payload — a texture's pixels at four bytes each, or a
        /// segment's vertex arrays — so an unbounded queue only moves the memory problem; the
        /// reader pauses when it is full, exactly as the mesh rip's does.
        /// </summary>
        private const int QueueCapacity = 8;

        /// <summary>
        /// The rip in flight, or <c>null</c>.
        /// </summary>
        NetworkRun _run;

        /// <summary>
        /// Whether a rip is running.
        /// </summary>
        public bool IsRipping => _run != null;

        /// <summary>
        /// How long a single frame may spend advancing a rip, in milliseconds.
        /// A budget rather than a fixed count of edges: a junction of a wide road costs many times
        /// what a straight footpath does, so a fixed count would stutter on exactly the parts of a
        /// city that are worth watching.
        /// </summary>
        private const double FrameBudgetMs = 12d;

        /// <summary>
        /// The event triggered when the system instance is destroyed.
        /// A rip in flight holds an open file, so it has to be closed here — the user quitting to
        /// the menu mid-rip is otherwise a truncated <c>networks.jsonl</c>.
        /// </summary>
        protected override void OnDestroy()
        {
            NetworkRun run = _run;
            _run = null;

            if (run != null)
            {
                _log.Info($"Network rip abandoned at {run.Index}/{run.Edges.Length} edge(s); the world was unloaded.");
                Instance.MeshRip.WarningSink = null;
                run.Writer?.Dispose();
                run.LaneWriter?.Dispose();

                // The writer is a live thread blocked on the queue, so abandoning the run without
                // closing it leaves it there for the rest of the session.
                //
                Drain(run);
                RipProgress.Clear();
            }

            base.OnDestroy();
        }

        /// <summary>
        /// Advance any rip in progress by one frame's worth. (The progress indicator is pumped by
        /// <c>RipOrchestratorSystem</c>, which owns the rip's UX.)
        /// </summary>
        protected override void OnUpdate()
        {
            NetworkRun run = _run;
            if (run != null) Advance(run);
        }

        /// <summary>
        /// Start a network rip, returning at once.
        /// </summary>
        /// <param name="outputDirectory">The bundle root to write into.</param>
        /// <param name="textureSizeCap">The longest edge a written texture may have, <c>0</c> for no cap, or negative to write no textures.</param>
        /// <param name="completed">Receives the finish summary instead of a dialog when a pipeline drives the rip.</param>
        /// <param name="surfaces">Whether to assemble the road/rail/path surfaces (networks.jsonl + networks/).</param>
        /// <param name="laneGeometry">Whether to bake lane-drawn furniture (lanemeshes layer).</param>
        /// <param name="laneDecals">Whether the lane catalogue carries decal parts — road markings and wear.</param>
        /// <returns>What the caller should tell the user.</returns>
        public string BeginRip(string outputDirectory, int textureSizeCap = 2048, Action<RipOutcome> completed = null,
                               bool surfaces = true, bool laneGeometry = true, bool laneDecals = true)
        {
            if (_run != null) return "A network rip is already running.";
            if (!surfaces && !laneGeometry) return "Nothing selected: both the network surfaces and the lane geometry are deselected.";

            // The material table has one owner at a time. A cross-section piece reads through the
            // same `MeshRipSystem.ReadMesh` a building does, and that only resolves a material when
            // a material run is in flight — so without one, every road's primitives keep the
            // synthetic `<piece>_mat0` id, nothing declares it, and the roads import untextured.
            //
            if (Instance.MeshRip.IsRipping)
                return "A mesh rip is running. Wait for it to finish — the two share the material table.";

            RipProgress.Report(RipProgress.Phase.Scan);
            // Keyed by piece entity; entities can be reused across runs, so the cache is per-rip.
            //
            _pieceGeometry.Clear();
            _rotatedEdges = 0;
            _roundaboutParts = 0;
            _skipBottomPieces = 0;
            _railPieces = 0;
            _emptyPieces = 0;
            _piecesFromAsset = 0;
            _pieceFromAssetNames.Clear();
            _emptyPieceNames.Clear();
            _orphanCaps = 0;
            _pipelineCompositions = 0;
            _lowerBottomPieces = 0;
            _raiseTopPieces = 0;
            _conformLoweredVerts = 0;
            _conformKeptVerts = 0;
            _conformRaisedVerts = 0;
            _conformOutOfWindowTris = 0;
            _unconformedPieces = 0;
            _elevatedUnconformedPieces = 0;
            _smoothTopPieces = 0;
            _smoothTopVerts = 0;
            _authoredFramePieces = 0;
            _rebuiltFramePieces = 0;
            _pinnedFrameVerts = 0;
            _conformProbes.Clear();
            _sectionProbes.Clear();

            // A deselected half simply contributes an empty work list; the pipeline shares the
            // rest — writers, materials, progress — unchanged.
            //
            Entity[] edges = Array.Empty<Entity>(), orphans = Array.Empty<Entity>(), lanes = Array.Empty<Entity>();

            if (surfaces)
            {
                NativeArray<Entity> entities = _edgeQuery.ToEntityArray(Allocator.TempJob);
                try
                {
                    edges = entities.ToArray();
                }
                finally
                {
                    entities.Dispose();
                }

                NativeArray<Entity> orphanEntities = _orphanQuery.ToEntityArray(Allocator.TempJob);
                try
                {
                    orphans = orphanEntities.ToArray();
                }
                finally
                {
                    orphanEntities.Dispose();
                }
            }

            if (laneGeometry)
            {
                NativeArray<Entity> laneEntities = _laneQuery.ToEntityArray(Allocator.TempJob);
                try
                {
                    lanes = laneEntities.ToArray();
                }
                finally
                {
                    laneEntities.Dispose();
                }
            }

            NetworkRun run = new()
            {
                Edges = edges,
                Orphans = orphans,
                Lanes = lanes,
                OutputDirectory = outputDirectory,
                MeshDirectory = IOUtils.CombinePath(outputDirectory, "networks"),
                LaneMeshDirectory = IOUtils.CombinePath(outputDirectory, "lanemeshes"),
                // A deselected half's writer is never created: constructing it would truncate a
                // file an earlier rip legitimately left there.
                Writer = surfaces ? new NetworkWriter(IOUtils.CombinePath(outputDirectory, "networks.jsonl")) : null,
                LaneWriter = laneGeometry ? new NetworkWriter(IOUtils.CombinePath(outputDirectory, "lanemeshes.jsonl")) : null,
                Materials = Instance.MaterialRip,
                IncludeLaneDecals = laneDecals,
                Completed = completed
            };

            run.Report.AppendLine($"Network edges: {edges.Length}");

            // Materials ride along, as they do for meshes: a piece's surface assets are reached
            // through the very render prefab its geometry came from. The writer runs off the main
            // thread because a texture is read back on it and compressed off it, and it serialises
            // the segment meshes too so that each one is written after the textures it names.
            //
            run.Queue = new BlockingCollection<NetworkItem>(QueueCapacity);
            Instance.MaterialRip.Begin(outputDirectory, textureSizeCap,
                                       texture => Enqueue(run, new NetworkItem { Texture = texture }));

            // Partial reads inside `ReadMesh` (lane part meshes read this way) must land in this
            // run's warnings — without a mesh run in flight they had nowhere to go (§10).
            //
            Instance.MeshRip.WarningSink = run.Skipped;

            run.Encoder = Task.Run(() => Encode(run));

            _run = run;
            RipProgress.Report(RipProgress.Phase.Networks, 0, edges.Length + orphans.Length + lanes.Length);

            return $"Ripping {edges.Length} network edge(s), {orphans.Length} orphan node(s) "
                 + $"and the drawn geometry of {lanes.Length} lane(s).\n\n"
                 + "Progress shows in the corner; a dialog reports the result when it finishes.";
        }







    }
}
