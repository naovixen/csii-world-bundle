"""Generate the settings reference from the code: `python tools/gen_docs.py [--check]`.

Writes two files, both from `cs2beamng.settings` alone:

    docs/settings.md    every setting, laid out the way the application lays them out: its
                        plain name, its `--set` name, what it does, and its long form
    site/settings.json  the same, for the Pages site's command builder

The long form is `settings.DETAILS` — the audit prose that used to be printed under every
control in the UI. It is the right amount of detail in the wrong place; here is the right place.

`--check` regenerates into memory and fails if the files on disk differ, so CI can catch a
settings change that never reached the docs.
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "apps"))
sys.path.insert(0, os.path.join(ROOT, "tools"))

MD_PATH = os.path.join(ROOT, "docs", "settings.md")
JSON_PATH = os.path.join(ROOT, "site", "settings.json")

HEADER = """<!-- GENERATED by tools/gen_docs.py from cs2beamng/settings.py - do not edit by hand -->
# cs2beamng settings

Every knob the level builder has, what it defaults to, and - where the answer needed an argument
- what was measured to arrive at that default.

You do not need this page to build a level. It is the reference for the person tuning one, and
for `--set`:

```
cs2beamng build <bundle> --out <levels>/<name> --preset high --set foliage_density=60
```

**It is laid out the way the application is**, so a setting you saw on screen is under the same
heading here: the handful of things you have to supply, then one section per part of the level,
then the build and tuning numbers, then the few settings that have no control of their own
because something else on screen sets them. Each entry leads with the name the application shows
and carries its `--set` name beside it.

Settings are saved in `~/.cs2beamng/settings.json` and are the same for the UI and the CLI, so a
headless build and a UI build with the same settings produce the same level.

"""


# The page's shape is the SCREEN's shape (`settings.SECTIONS`), plus the two buckets a section
# list does not have: what the app asks for before any of it, and what has no control at all.
# `settings.section_of` is the one function that decides which of them a key is in, so the page
# and the app cannot file the same setting differently.
BASICS_TITLE = (
    "basics",
    "The things you have to supply",
    "The application asks for these before anything else, and finds most of them for you.",
)
DRIVEN_TITLE = (
    "driven",
    "Set for you by something else",
    "These have no control of their own: another one on screen sets them. They keep "
    "their `--set` name, and `--set` stays literal - it does exactly what you tell "
    "it, driving rule or not.",
)


def render_markdown(settings_mod):
    parts = [HEADER.format(basic=len(settings_mod.BASICS), total=len(settings_mod.SCHEMA))]

    parts.append("## Presets\n")
    parts.append("| Preset | What it costs |\n| --- | --- |")
    for name in ("ultra", "high", "performance", "medium", "low"):
        if name in settings_mod.PRESET_INFO:
            parts.append(f"| `{name}` | {settings_mod.PRESET_INFO[name]} |")
    parts.append("")
    parts.append(
        "A preset is a whole-dict override applied on top of the defaults; your own "
        "changes after picking one stick, and the preset row then reads `custom`.\n"
    )

    for where, title, note in _page_sections(settings_mod):
        keys = [k for k in settings_mod.SCHEMA if settings_mod.section_of(k) == where]
        if not keys:
            continue
        parts.append(f"## {title}\n")
        if note:
            parts.append(f"{note}\n")
        for key in keys:
            parts.extend(_entry(settings_mod, key))
    return "\n".join(parts).rstrip() + "\n"


def _page_sections(settings_mod):
    """`[(where, title, note)]` in the order the screen has them."""
    out = [BASICS_TITLE]
    for section in settings_mod.SECTIONS:
        note = section.get("note") or section.get("tagline") or ""
        out.append((section["id"], section["label"], note))
    out.append(DRIVEN_TITLE)
    return out


def _entry(settings_mod, key):
    """One setting: its plain name, its `--set` name, what it does, and why its default is that."""
    default, kind, help_text = settings_mod.SCHEMA[key]
    label = settings_mod.LABELS.get(key, key)
    blurb = settings_mod.BLURBS.get(key, help_text)
    kind_text = kind.replace("choice:", "one of ").replace("|", ", ")
    shown_default = '""' if default is None else f"`{default!r}`"
    lines = [f"### {label}\n", f"`--set {key}=`\n", f"{blurb}\n"]
    if key in settings_mod.DRIVEN_BY:
        lines.append(f"*No control of its own - set by {settings_mod.DRIVEN_BY[key]}.*\n")
    unit = settings_mod.UNITS.get(key)
    lines.append(f"*{kind_text}{f' in {unit}' if unit else ''}, default {shown_default}*\n")
    # `help` is the one-liner the CLI prints and is written for a page with no label beside it.
    # It earns a line here only where it says MORE than the blurb does — printing "Buildings"
    # under "Houses, offices, factories and everything else your city has built" is noise, and a
    # reference page that repeats itself is one people stop reading.
    if help_text and len(help_text) > len(blurb):
        lines.append(f"{help_text}\n")
    detail = settings_mod.DETAILS.get(key)
    if detail:
        lines.append("<details><summary>Why this default</summary>\n")
        lines.append(f"{detail}\n")
        lines.append("</details>\n")
    return lines


def render_json(settings_mod):
    """What the site's command builder needs: enough to compose a `--set` line, no prose."""
    out = {
        "version": __import__("cs2beamng").__version__,
        "basic": list(settings_mod.BASIC),
        "presets": {name: settings_mod.PRESET_INFO.get(name, "") for name in settings_mod.PRESETS},
        "settings": [],
    }
    for key, (default, kind, help_text) in settings_mod.SCHEMA.items():
        # `label` and `blurb` as well as `help`: the site shows a person the same words the
        # application does, and used to print the raw key with its underscores knocked out.
        entry = {
            "key": key,
            "kind": kind.split(":", 1)[0],
            "default": default,
            "help": help_text,
            "label": settings_mod.LABELS.get(key, key),
            "blurb": settings_mod.BLURBS.get(key, help_text),
            "section": settings_mod.section_of(key),
            "tier": "basic" if key in set(settings_mod.BASIC) else "advanced",
        }
        if kind.startswith("choice:"):
            entry["choices"] = kind.split(":", 1)[1].split("|")
        out["settings"].append(entry)
    return json.dumps(out, indent=1, sort_keys=False) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(prog="gen_docs", description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the files on disk are stale")
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)

    from cs2beamng import settings as settings_mod

    wanted = {MD_PATH: render_markdown(settings_mod), JSON_PATH: render_json(settings_mod)}
    stale = []
    for path, text in wanted.items():
        current = open(path, encoding="utf-8").read() if os.path.isfile(path) else None
        if current == text:
            continue
        if args.check:
            stale.append(os.path.relpath(path, ROOT))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w", encoding="utf-8", newline="\n").write(text)
        print(f"wrote {os.path.relpath(path, ROOT)} ({len(text):,} chars)")
    if stale:
        print(f"stale: {', '.join(stale)} - run `python tools/gen_docs.py`", file=sys.stderr)
        return 1
    if args.check:
        print("docs are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
