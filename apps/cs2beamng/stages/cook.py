"""Stage `cook` — BeamNG's own headless mesh compiler over the level we just wrote, so the
first in-game load does not spend minutes parsing COLLADA.

What the game does on a cold load of our level: it parses every `.dae` (2,832 tiles, 2.1 GB of
XML on the full city) into its binary `.cdae` (`temp/levels/<name>/art/shapes/...`) — 210 s
of "objects" in `beamng.log`'s `Level loaded in` line, all of it stall — then cooks the
textures. `BeamNG.drive.exe -compilemeshes` (`lua/ge/extensions/util/compileMeshes.lua`)
does the first half without a window: it walks `-compileMeshesCustomPaths "levels/<name>/"`
in the game's virtual file system, compiles each `.dae` to a `.cdae` BESIDE it (which the
runtime loader prefers over compiling), and quits with `shutdown()`. `-compileMeshesNoCheck`
keeps it from failing the run because every vanilla `.dae` in the game's zips is "missed".
The texture-cache warmer the plan mentions (`-LoadSingleLevelForTextureCache`) is not in
0.39's shipped Lua (`extensions/test/singleLevel.lua` is absent), so textures still cook on
the first load — 260 textures in ~2 minutes of on-demand work, none of it a stall.

**The compiler writes materials of its own.** It runs without a level loaded, so it never
sees `art/cs2/main.materials.json`; the first shape it meets in each shape directory binds
names it does not know, and BeamNG's COLLADA importer then writes an auto-generated
`main.materials.json` BESIDE the shape — one opaque `diffuseColor 0.8` placeholder per unknown
name (`translucentBlendOp: None`). Loose files under `levels/` are all mounted at play time,
so those placeholders shadow our real definitions of the same names: load #10 (2026-08-16)
drew `LaneMarkingsEUNA` (crosswalks, "45"), `LaneLine`, `CarLane`, `RoadParts` … as flat
light-grey opaque boxes while `NA_RoadArrow`, which no first-tile bound, blended correctly.
We never write a materials file under `art/shapes/` (ours live in `art/cs2/` and
`art/terrains/`), so every `*.materials.json` found there is the compiler's: removed before
the run (a leftover would be loaded and trusted) and after it (`_remove_autogenerated`, also on
cancel/kill), and `validate_level` fails the build if one survives or a name is defined twice.

**Incremental since A4.** `dae.write_shape` rewrites a `.dae` only when its bytes differ, and
drops the `.cdae` only on that path, so a `.cdae` at least as new as its `.dae` is current —
which is exactly the state `compileMeshes.lua` is written for (*"keep in mind that existing
.cdae will be reused. Delete them beforehand if a clean state is required"*). This stage now
compiles the changed shapes only, and returns without starting the engine at all when there are
none: that one behaviour is 6m26s of a 14-minute no-op rebuild.

**Skippable since version 3**, which is a different claim. "Nothing to compile" still cost the
tail — a `scan_dae` of every `.dae` in the level to rebuild `shape_ladders.json` (4.4 GiB of
XML read and regexed, ~12 s warm on the reference city) and a walk of BeamNG's `temp/` — and
still reported itself `done`, so the cook was the one step of a no-op rebuild that visibly ran.
It declares `shapes:` now (`pipeline/state.py`), a stat walk of `art/shapes/**/*.{dae,cdae}`,
and a build where no shape moved skips the stage whole. The ladder index is merged rather than
rewritten either way, so the shapes this cook is not compiling are not re-read to learn numbers
that cannot have changed.

Progress is the `.cdae` files appearing under the level's `art/shapes/` beyond the ones kept,
polled every `POLL_SECONDS`; the compiler logs to the same `beamng.log` but overwriting it is its business,
not ours. Cancel kills the process. The stage SKIPS (never fails the build) when: the setting
is off, no executable is found (`beamng_exe` or the Steam libraries), the level does not live
under a BeamNG userfolder (the compiler can only see the game's virtual FS), or a BeamNG
process is already running (one instance per userfolder). Each skip is a log line and a
`skipped` reason in the report.
"""

import json
import os
import subprocess
import sys
import time

from csiibundle.bake.progress import Cancelled

from .. import settings as settings_mod

# The ladder index is written in the format `budget` reads, and importing it is how the two stay
# in step. It used to be `tools/level_budget.py` reached through a __file__ climb, which meant a
# non-editable `pip install .` could not import this stage at all.
from ..beamng import budget as level_budget
from . import Stage

STAGE_KEY = "cook"
POLL_SECONDS = 2.0
STARTUP_GRACE_SECONDS = 180.0  # the engine boots (~20-40 s) before the first .cdae lands
STALL_SECONDS = 600.0  # no new .cdae for this long -> give up on the compiler
SHAPE_DIRS = ("art", "shapes")


def enabled(settings):
    return bool(settings.get("cook", False))


def units(census, settings):
    return None


def run(ctx, progress):
    started = time.monotonic()
    level_dir = os.path.abspath(ctx.level_dir)
    level_name = ctx.settings["level_name"]

    exe = _engine_exe(settings_mod.find_beamng_exe(ctx.settings))
    if not exe:
        return _skip(progress, "no BeamNG executable found (set beamng_exe)", started)
    userfolder = _userfolder_of(level_dir)
    if userfolder is None:
        return _skip(
            progress,
            f"{level_dir} is not under a BeamNG userfolder's levels/; the compiler only sees the game's own file system",
            started,
        )
    if _beamng_running():
        return _skip(
            progress,
            "BeamNG is already running (one instance per userfolder); close it and rebuild, or load the level and let it compile",
            started,
        )

    shapes_dir = os.path.join(level_dir, *SHAPE_DIRS)
    daes = _find(shapes_dir, ".dae")
    if not daes:
        return _skip(progress, "no .dae shapes in the level", started)
    # Only the shapes whose `.dae` actually changed. `dae.write_shape` rewrites a file solely
    # when its bytes differ and drops the `.cdae` only then, so a `.cdae` at least as new as its
    # `.dae` describes exactly that geometry — and the compiler is built to reuse it
    # (`compileMeshes.lua`: "existing .cdae will be reused"). Removing all of them every build
    # was the whole 6m26s cook on a rebuild that changed no geometry.
    todo = [path for path in daes if _needs_compile(path)]
    removed = 0
    for path in todo:  # a leftover beside a REWRITTEN .dae is the old mesh
        cdae = os.path.splitext(path)[0] + ".cdae"
        if os.path.isfile(cdae):
            try:
                os.remove(cdae)
                removed += 1
            except OSError:
                pass
    if not todo:
        progress.log(
            f"cook: all {len(daes)} shapes already have a current .cdae; nothing to compile"
        )
        tidy = _tidy(ctx, level_dir, level_name, shapes_dir, progress, rescan=())
        return {
            "compiled": 0,
            "shapes": len(daes),
            "upToDate": len(daes),
            "skipped": "nothing changed",
            **tidy,
            "seconds": round(time.monotonic() - started, 1),
        }
    stale_materials = _remove_autogenerated(shapes_dir)
    if stale_materials:
        progress.log(
            f"cook: removed {len(stale_materials)} auto-generated materials file(s) left by an earlier run: "
            + ", ".join(os.path.relpath(p, level_dir) for p, _names in stale_materials)
        )

    # -compileMeshesNoCache: the compiler otherwise copies every .cdae into <userfolder>/
    # collada_cache/<sha1>.cdae as well — a second 1.6 GB of the same bytes on a full city.
    args = [
        exe,
        "-headless",
        "-nosteam",
        "-compilemeshes",
        "-compileMeshesCustomPaths",
        f"levels/{level_name}/",
        "-compileMeshesNoCheck",
        "-compileMeshesNoCache",
    ]
    progress.log(
        f"cook: {os.path.basename(exe)} -compilemeshes levels/{level_name}/ ({len(todo)} of "
        f"{len(daes)} shapes need compiling, {len(daes) - len(todo)} already current"
        f"{', ' + str(removed) + ' stale .cdae removed' if removed else ''})"
    )
    progress.begin("cook: compiling shapes to .cdae", total=len(todo), unit="shapes")
    creation = {}
    if sys.platform.startswith("win"):
        creation["creationflags"] = getattr(subprocess, "CREATE_NO_WINDOW", 0)
    try:
        proc = subprocess.Popen(
            args,
            cwd=os.path.dirname(exe),
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            **creation,
        )
    except OSError as exc:
        return _skip(progress, f"could not start {exe}: {exc}", started)

    done = 0
    base_cdae = len(
        _find(shapes_dir, ".cdae")
    )  # the ones kept: progress counts what appears ON TOP
    last_change = time.monotonic()
    try:
        while True:
            try:
                progress.check()
            except Cancelled:
                _kill(proc)
                raise
            now_done = max(0, len(_find(shapes_dir, ".cdae")) - base_cdae)
            if now_done != done:
                progress.advance(now_done - done)
                done = now_done
                last_change = time.monotonic()
            code = proc.poll()
            if code is not None:
                break
            waited = time.monotonic() - last_change
            if (done == 0 and waited > STARTUP_GRACE_SECONDS) or (
                done > 0 and waited > STALL_SECONDS
            ):
                _kill(proc)
                progress.end(f"compiler stalled after {done}/{len(todo)} shapes; killed")
                return {
                    "compiled": done,
                    "shapes": len(daes),
                    "toCompile": len(todo),
                    "skipped": "stalled",
                    "exe": exe,
                    "autogeneratedMaterialsRemoved": len(_remove_autogenerated(shapes_dir)),
                    "_norecord": True,  # a half-cooked level is not a state to skip from
                    "seconds": round(time.monotonic() - started, 1),
                }
            time.sleep(POLL_SECONDS)
    finally:
        if proc.poll() is None:
            _kill(proc)
        # the compiler's placeholder materials (see the module docstring): never leave one behind
        generated = _remove_autogenerated(shapes_dir)
    if generated:
        names = sorted({n for _p, ns in generated for n in ns})
        progress.log(
            f"cook: removed {len(generated)} auto-generated materials file(s) the compiler wrote beside the shapes "
            f"({len(names)} placeholder name(s): {', '.join(names[:6])}{', ...' if len(names) > 6 else ''})"
        )
    have = len(_find(shapes_dir, ".cdae"))
    done = max(0, have - base_cdae)
    progress.end(
        f"{done}/{len(todo)} changed shapes compiled ({have}/{len(daes)} now have a .cdae), exit code {code}"
    )
    tidy = _tidy(ctx, level_dir, level_name, shapes_dir, progress, rescan=todo)
    return {
        "compiled": done,
        "shapes": len(daes),
        "toCompile": len(todo),
        "upToDate": len(daes) - len(todo),
        "withCdae": have,
        "exitCode": code,
        "exe": exe,
        "autogeneratedMaterialsRemoved": len(generated),
        **tidy,
        "seconds": round(time.monotonic() - started, 1),
    }


def _engine_exe(found):
    """The engine binary itself. The Steam-facing `BeamNG.drive.exe` in the install root is a
    launcher that starts `Bin64/BeamNG.drive.x64.exe` and returns, which would end our wait
    at once; drive the engine directly when it is there."""
    if not found:
        return None
    root = os.path.dirname(found)
    if sys.platform.startswith("win"):
        engine = os.path.join(root, "Bin64", "BeamNG.drive.x64.exe")
        if os.path.basename(found).lower() == "beamng.drive.exe" and os.path.isfile(engine):
            return engine
    return found


def _needs_compile(dae_path):
    """Whether this `.dae` still has to go through the compiler: no `.cdae` beside it, or one
    older than the `.dae` (which only happens when the shape's bytes really changed, because
    `dae.write_shape` leaves an unchanged file — mtime included — alone)."""
    cdae = os.path.splitext(dae_path)[0] + ".cdae"
    try:
        return os.path.getmtime(cdae) < os.path.getmtime(dae_path)
    except OSError:
        return True


def _skip(progress, reason, started):
    """A bail-out, and never a recorded state (`_norecord`): every reason this stage gives up is
    about the MACHINE, not about the level — no engine installed, one already running, a level
    outside the userfolder. None of them shows up in `shapes:` or in `settings_keys`, so caching
    the bail-out would leave the shapes uncooked however many builds followed."""
    progress.log(f"cook: skipped: {reason}")
    return {"skipped": reason, "_norecord": True, "seconds": round(time.monotonic() - started, 1)}


def _write_ladder_index(level_dir, shapes_dir, rescan=()):
    """`shape_ladders.json` — every shape's detail ladder and collision count, read out of the
    `.dae` sources while they are still there. Returns `(shapes, rescanned)`.

    **`keep_dae: false` deletes the only place those numbers live.** `level_budget` derives the
    triangles a level actually draws by walking each shape's `<geometry>` blocks, so a level whose
    sources were dropped could report its bytes and not one triangle — the gate this project has
    used since A5 would silently read zero.

    So the index is **merged, never rewritten from scratch**, on two counts:

    * `scan_dae` reads each file whole and regexes it — 4.4 GiB and ~12 s of it on the reference
      city, paid on every build including one that compiled nothing. Only the shapes this cook is
      about to compile can have changed (`_needs_compile` is exactly "the `.dae` moved"), so every
      other entry is carried over from the file that is already there.
    * a shape whose `.dae` a previous `keep_dae: false` build removed keeps its entry as long as
      its `.cdae` is still in the level. Rewriting the file from the surviving sources dropped
      every one of those numbers — the very case the index exists for.
    """
    out = os.path.join(level_dir, level_budget.LADDER_INDEX)
    try:
        with open(out, encoding="utf-8") as handle:
            previous = (json.load(handle) or {}).get("shapes") or {}
    except (OSError, ValueError):
        previous = {}
    rescan = {os.path.abspath(p) for p in rescan}
    shapes = {}
    rescanned = 0
    for path in _find(shapes_dir, ".dae"):
        rel = os.path.relpath(path, level_dir).replace("\\", "/")
        carried = previous.get(rel)
        if carried is not None and os.path.abspath(path) not in rescan:
            shapes[rel] = carried
            continue
        levels, collision = level_budget.scan_dae(path)
        shapes[rel] = {
            "levels": {str(px): int(t) for px, t in (levels or {}).items()},
            "collision": int(collision or 0),
        }
        rescanned += 1
    for rel, entry in previous.items():  # source gone, cooked shape still there
        if rel in shapes:
            continue
        cdae = os.path.join(level_dir, *(os.path.splitext(rel)[0] + ".cdae").split("/"))
        if os.path.isfile(cdae):
            shapes[rel] = entry
    with open(out, "w", encoding="utf-8", newline="\n") as handle:
        json.dump({"schema": "cs2beamng.shape_ladders/1", "shapes": shapes}, handle, sort_keys=True)
    return len(shapes), rescanned


def _tidy(ctx, level_dir, level_name, shapes_dir, progress, rescan=()):
    """A8/P7 — the two disk sweeps, both after the cook so nothing they remove is still needed."""
    out = {}
    settings = getattr(ctx, "settings", None) or {}
    # BEFORE any sweep: the ladder index is read from the `.dae` sources one of them deletes
    try:
        out["shapeLaddersIndexed"], out["shapeLaddersScanned"] = _write_ladder_index(
            level_dir, shapes_dir, rescan
        )
    except (OSError, ValueError) as exc:
        progress.log(
            f"cook: could not write the shape ladder index ({exc}); "
            f"`level_budget` will not be able to count triangles if the sources go"
        )
    if settings.get("sweep_temp", True):
        files, freed = _sweep_temp(level_dir, level_name, shapes_dir)
        out["tempCdaeRemoved"] = files
        out["tempMiBFreed"] = round(freed / 1048576.0, 1)
        if files:
            progress.log(
                f"cook: swept {files:,} stale .cdae ({freed / 1048576:,.0f} MiB) out of BeamNG's "
                f"temp/ — cooked shapes this level no longer has a source for"
            )
    if not settings.get("keep_dae", False):
        files, freed = _drop_dae_sources(shapes_dir)
        out["daeSourcesRemoved"] = files
        out["daeMiBFreed"] = round(freed / 1048576.0, 1)
        if files:
            progress.log(
                f"cook: removed {files:,} .dae sources ({freed / 1048576:,.0f} MiB) that have a "
                f"current .cdae — the engine loads the cooked file, never the source "
                f"(`keep_dae` keeps them)"
            )
    return out


def _sweep_temp(level_dir, level_name, shapes_dir):
    """Delete cooked shapes in BeamNG's `temp/` that the level no longer has a source for.

    **BeamNG never prunes it.** `temp/levels/<name>/` accumulates a `.cdae` for every shape any
    build ever wrote, so a folder that has been rebuilt for a fortnight holds every shape that has
    ever existed: measured 2026-08-19, 9,047 cooked files where the level had 4,289 — 4,998 MiB, of
    which more than half was for shapes that no longer exist. It costs no RAM (the engine loads
    only what the level references) and it is 2.5 GB of disk.

    Only files under THIS level's temp folder whose `.dae`/`.cdae` counterpart is gone from the
    level are removed. Returns `(files, bytes)`.
    """
    root = os.path.dirname(os.path.dirname(os.path.abspath(level_dir)))  # <userfolder>/levels/..
    temp = os.path.join(root, "temp", "levels", level_name)
    if not os.path.isdir(temp) or not os.path.isdir(shapes_dir):
        return 0, 0
    keep = set()
    for path in _find(shapes_dir, ".dae") + _find(shapes_dir, ".cdae"):
        keep.add(os.path.splitext(os.path.relpath(path, level_dir))[0].replace("\\", "/").lower())
    files = freed = 0
    for base, _dirs, names in os.walk(temp):
        for name in names:
            if not name.lower().endswith(".cdae"):
                continue
            path = os.path.join(base, name)
            stem = os.path.splitext(os.path.relpath(path, temp))[0].replace("\\", "/").lower()
            if stem in keep:
                continue
            try:
                size = os.path.getsize(path)
                os.remove(path)
            except OSError:
                continue
            files += 1
            freed += size
    return files, freed


def _drop_dae_sources(shapes_dir):
    """Delete every `.dae` that has a `.cdae` at least as new beside it. Returns `(files, bytes)`.

    **The engine loads the cooked file and never the source**, and this has vanilla's own
    precedent: 182 of BeamNG's 6,361 shipped `.cdae` have no `.dae` at all (74 in `Industrial.zip`
    alone), while 0 shipped `.dae` lack a `.cdae`. On the reference city the sources are 5,452 MiB
    against the cooked 4,173.

    A `.dae` with no current `.cdae` is NEVER removed — that would delete the only copy of a shape
    the cook did not reach.
    """
    files = freed = 0
    for path in _find(shapes_dir, ".dae"):
        cdae = os.path.splitext(path)[0] + ".cdae"
        try:
            if not os.path.isfile(cdae) or os.path.getmtime(cdae) < os.path.getmtime(path):
                continue
            size = os.path.getsize(path)
            os.remove(path)
        except OSError:
            continue
        files += 1
        freed += size
    return files, freed


def _remove_autogenerated(shapes_dir):
    """Delete every `*.materials.json` under `shapes_dir` — none is ours (see the module
    docstring). Returns `[(path, [material names])]` for the log; a file that cannot be read
    still counts, with no names."""
    removed = []
    for path in _find(shapes_dir, ".materials.json"):
        names = []
        try:
            with open(path, encoding="utf-8") as handle:
                doc = json.load(handle)
            if isinstance(doc, dict):
                names = [str(v.get("name") or k) for k, v in doc.items() if isinstance(v, dict)]
        except (OSError, ValueError):
            pass
        try:
            os.remove(path)
        except OSError:
            continue
        removed.append((path, names))
    return removed


def _find(root, suffix):
    out = []
    for dirpath, _dirs, files in os.walk(root):
        for name in files:
            if name.lower().endswith(suffix):
                out.append(os.path.join(dirpath, name))
    return out


def _userfolder_of(level_dir):
    """The BeamNG userfolder `level_dir` lives in (`<userfolder>/levels/<name>`), or None."""
    parent = os.path.dirname(level_dir)
    if os.path.basename(parent).lower() != "levels":
        return None
    userfolder = os.path.dirname(parent)
    known = [os.path.abspath(p) for p in settings_mod.candidate_userfolders()]
    if os.path.abspath(userfolder) in known:
        return userfolder
    # a userfolder we did not guess but which is one: it holds the game's settings tree
    if os.path.isdir(os.path.join(userfolder, "settings")) or os.path.isfile(
        os.path.join(userfolder, "beamng.log")
    ):
        return userfolder
    return None


def _beamng_running():
    try:
        if sys.platform.startswith("win"):
            out = subprocess.run(
                ["tasklist", "/FI", "IMAGENAME eq BeamNG.drive.x64.exe", "/NH"],
                capture_output=True,
                text=True,
                timeout=15,
            ).stdout
            return "BeamNG.drive.x64.exe" in out
        out = subprocess.run(
            ["pgrep", "-f", "BeamNG.drive"], capture_output=True, text=True, timeout=15
        ).stdout
        return bool(out.strip())
    except Exception:
        return False


def _kill(proc):
    try:
        proc.kill()
        proc.wait(timeout=10)
    except Exception:
        pass


# version 2: A8/P7 — after cooking, sweep BeamNG's `temp/` of cooked shapes the level no longer
# has a source for (it never prunes them itself), and optionally drop the `.dae` sources the
# engine never loads
# version 3: the stage is INCREMENTAL. It is the one stage that is a function of the written
# shapes rather than of the bundle, so it declares `shapes:` — a stat walk of the level's
# `.dae`/`.cdae` — and a build where no shape moved skips it whole, ladder index and sweeps
# included, and reports `unchanged` like every other stage instead of `done`.
STAGE = Stage(
    STAGE_KEY,
    "Cook (BeamNG mesh compiler)",
    enabled,
    units,
    run,
    inputs=("shapes:",),
    settings_keys=("sweep_temp", "keep_dae"),
    version=3,
)
